"""Browser export of the shipped detector: address model + page model from one blend2 split.

python -m models.export_page [--models data/models] [--split 0] [--processed data/processed]

Reads the models ``python -m experiments.blend2 --save-models DIR`` pickled for split k (the
address model ``a``, the page model ``b`` that shares ``a``'s text scorers, both isotonic maps
and the blend thresholds) and writes:

- ``js/data/tier_a_hybrid.json``: the address model (same format as ``models.export_hybrid``,
  thresholds from split k's cal side), used before the page has loaded;
- ``js/data/tier_b_page.json``: the page model's trees, reason rules, both isotonic maps, the
  tie-break and the blend thresholds, used once the content script has the page's HTML;
- ``tests/fixtures/hybrid_parity.json`` (address model, as before) and
  ``tests/fixtures/page_parity.json``: Python's scores, verdicts and reasons for every page of
  ``tests/fixtures/html_parity.json``, which pytest and the JS suite both reproduce.

The verdict after the page loads is the ``agree`` rule of ``experiments.blend2``: dangerous if
the address model alone is over its dangerous threshold (that verdict acts before the page loads)
or the blended score is over the blend's dangerous threshold; suspicious if the blended score is
over the blend's suspicious threshold and, on a page with usable HTML, the address model is also
over its own suspicious threshold (two checks must agree before a banner). The blended score is
the calibrated page-model score when the page has usable HTML, else the calibrated address score.
"""

