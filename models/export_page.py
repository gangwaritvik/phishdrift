PAGE_FILE = JS_DATA / "tier_b_page.json"
# Verdict rule shipped (experiments.blend2): "agree" = a suspicious banner on a page with usable
# HTML needs both the page model and the address model over their 1% thresholds.
RULE = "agree"
PAGE_PARITY_FILE = ROOT / "tests" / "fixtures" / "page_parity.json"
HTML_PARITY_FILE = ROOT / "tests" / "fixtures" / "html_parity.json"


class _Unpickler(pickle.Unpickler):
    """``experiments.blend2`` run as a script pickles its classes under ``__main__``."""

    def find_class(self, module: str, name: str):
        if module == "__main__":
            module = "experiments.blend2"
        return super().find_class(module, name)


def iso_payload(cal) -> dict:
    return {"x": cal.iso.X_thresholds_.tolist(), "y": cal.iso.y_thresholds_.tolist()}


def page_bundle(saved: dict, cfg: dict, k: int, metrics: dict) -> dict:
    b = saved["b"]
    names = list(b.columns)
    trees = compact_trees(b.gbdt.model.booster_)
    t1, t01 = saved["thr"]["blend"]
    a1, a01 = saved["thr"]["a"]
    if cfg["eval"].get("suspicious_rule") == "worst_source":  # reports/threshold_transfer.md
        t1, a1 = saved["thr"]["blend_ws"][0], saved["thr"]["a_ws"][0]
    return {
        "note": "Generated by `python -m models.export_page`. Do not edit by hand.",
        "created": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "model": "page model: lightgbm on tier A + tier B + the address model's text scores",
        "split": k,
        "names": names,
        "trees": trees,
        "expected_value": expected_value(trees),
        "reasons": reason_rules(names),
        "explain": dict(cfg["explain"]),
        "isotonic_page": iso_payload(saved["cal_b"]),
        "isotonic_address": iso_payload(saved["cal_a"]),
        "tie": TIE,
        "thresholds": {"suspicious": t1, "dangerous": t01},
        "address_thresholds_calibrated": {"suspicious": a1, "dangerous": a01},
        "rule": RULE,
        "metrics": metrics,
    }


def blend_metrics(saved: dict, sets: dict, cfg: dict) -> dict:
    targets, min_neg = cfg["eval"]["target_fprs"], cfg["eval"]["min_negatives"]
    pair = list(saved["thr"]["blend"])
    if cfg["eval"].get("suspicious_rule") == "worst_source":
        pair[0] = saved["thr"]["blend_ws"][0]
    thr = dict(zip(targets, pair, strict=True))
    out = {}
    for name, frame in sets.items():
        s = Scored(frame, saved["a"], saved["b"], saved["cal_a"], saved["cal_b"])
        y = frame["label"].to_numpy()
        for tag, m in (("", np.ones(len(y), bool)), (":html", s.html)):
            if m.any() and len(np.unique(y[m])) == 2:
                row = evaluate(y[m], s.blend[m], targets, min_neg, thr)
                out[name + tag] = {key: _clean(v) for key, v in row.items()}
    return out


def page_frame(cases: list[dict], lists: Lists, fitted) -> pd.DataFrame:
    rows = [extract(c["url"], build_html(c["html"]), lists=lists, fitted=fitted) for c in cases]
    frame = pd.DataFrame(rows, columns=[*NAMES, *NAMES_B]).astype("float32")
    frame["has_html"] = frame[list(NAMES_B)].notna().any(axis=1).to_numpy()
    frame["_parts"] = [parse(c["url"], lists.platforms) for c in cases]
    frame["_text"] = [p.canon if p is not None else "" for p in frame["_parts"]]
    return frame


def page_parity(saved: dict, bundle: dict, a_bundle: dict, lists: Lists) -> dict:
    """Python's blended score, verdict and page reasons for every HTML parity page."""
    cases = json.loads(HTML_PARITY_FILE.read_text(encoding="utf-8"))["cases"]
    a, b = saved["a"], saved["b"]
    frame = page_frame(cases, lists, saved["fitted"])
    text = a.text_scores(frame)
    prob_a = a.gbdt.score(frame.assign(**text))
    prob_b = b.score(frame, text)
    x = frame.assign(**text)[bundle["names"]].to_numpy(dtype=np.float32)
    walked = probability(bundle["trees"], x)
    if np.max(np.abs(walked - prob_b)) > 1e-9:
        raise AssertionError("exported page trees differ from the fitted page model")
    s = Scored(frame, a, b, saved["cal_a"], saved["cal_b"])
    t = bundle["thresholds"]
    a_danger = prob_a >= a_bundle["thresholds"]["dangerous"]
    a_susp = prob_a >= a_bundle["thresholds"]["suspicious"]
    out = []
    for i, c in enumerate(cases):
        verdict = 2 if (a_danger[i] or s.blend[i] >= t["dangerous"]) else 0
        both = a_susp[i] or not s.html[i] or bundle["rule"] != "agree"
        if not verdict and s.blend[i] >= t["suspicious"] and both:
            verdict = 1
        why = []
        if s.html[i]:
            phi = contributions(bundle["trees"], x[i])
            why = reasons(phi, x[i], bundle["names"], bundle["reasons"], **bundle["explain"])
        out.append(
            {
                "index": i,  # position in tests/fixtures/html_parity.json
                "url": c["url"],
                "has_html": bool(s.html[i]),
                "prob_address": float(prob_a[i]),
                "prob_page": float(prob_b[i]) if s.html[i] else None,
                "blended": float(s.blend[i]),
                "verdict": verdict,
                "reasons": why,
            }
        )
    return {
        "note": "Generated by `python -m models.export_page`. Do not edit by hand.",
        "bundle_created": bundle["created"],
        "cases": out,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="models.export_page")
    ap.add_argument("--models", type=Path, default=Path("data/models"))
    ap.add_argument("--split", type=int, default=0)
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    cfg, lists = load_config("models"), load_lists()
    with open(a.models / f"blend2_split_{a.split}.pkl", "rb") as fh:
        saved = _Unpickler(fh).load()  # our own file, written by experiments.blend2
    _, cal, test, frames = split_frames(a.processed, a.split, lists)
    fitted = saved["fitted"]
    cal, test = (apply_fitted(f, fitted) for f in (cal, test))
    held = {n: apply_fitted(f, fitted) for n, f in frames.items()}
    a_bundle = address_bundle(saved["a"], cal, {"test": test, **held}, fitted, lists, cfg, a.split)
    a_doc = parity(a_bundle, saved["a"], saved["a"].gbdt.model.booster_, lists, fitted)

    page_sets = {"test": with_page_features(test, a.processed, "pool")}
    page_sets |= {n: with_page_features(f, a.processed, n) for n, f in held.items()}
    bundle = page_bundle(saved, cfg, a.split, blend_metrics(saved, page_sets, cfg))
    p_doc = page_parity(saved, bundle, a_bundle, lists)
    for path in write(a_bundle, a_doc, BUNDLE_FILE, PARITY_FILE):
        print(path, f"{path.stat().st_size / 1e6:.2f} MB")
    for path in write(bundle, p_doc, PAGE_FILE, PAGE_PARITY_FILE):
        print(path, f"{path.stat().st_size / 1e6:.2f} MB")
    rows = [{"split": a.split, "eval_set": n} | v for n, v in bundle["metrics"].items()]
    (a.reports / "tables").mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(a.reports / "tables" / "page_export.csv", index=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
