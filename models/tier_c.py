"""Tier C model for the hosted domain check: train on captured domains, export for JavaScript.

python -m models.tier_c train [--features data/processed/features_c.parquet] [--split 0]
python -m models.tier_c parity    # tests/fixtures/tier_c_parity.json (no data needed)

``train`` fits the same LightGBM as ``experiments.tier_c`` ("c_all") on one domain-grouped
split, takes the "suspicious" threshold from the FPR 1% point of the cal side and the isotonic
map from the same rows, and writes ``js/data/tier_c.json`` (feature order, trees, thresholds,
isotonic, reason sentences, brand list) plus ``tests/fixtures/tier_c_model_parity.json``. The
"dangerous" threshold (FPR 0.1%) is exported only when the cal side holds enough legitimate
domains to measure it (``eval.min_negatives`` false positives allowed at that FPR); otherwise it
is null and tier C can only say "suspicious".

``parity`` writes raw captured facts with the features Python computes from them, and the
parsers' inputs and outputs, for ``js/test/tier_c.test.js``.
"""

