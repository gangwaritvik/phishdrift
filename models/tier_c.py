def clean(v):
    """JSON-safe copy: NaN becomes null."""
    if isinstance(v, float):
        return None if math.isnan(v) else v
    if isinstance(v, dict):
        return {k: clean(x) for k, x in v.items()}
    if isinstance(v, list | tuple):
        return [clean(x) for x in v]
    return v


# --- training and export ---------------------------------------------------------------


def train(df: pd.DataFrame, cfg: dict, k: int = 0):
    """(model, calibrator, split frames) for split ``k`` of the eligible rows ``df``."""
    cc, ev = cfg["tier_c"], cfg["eval"]
    splits = grouped_splits(df, k + 1, cc["test_fraction"], cc["cal_fraction"], cc["seed"])
    side = splits[f"split_{k}"]
    train_df, cal, test = (df[(side == s).to_numpy()] for s in (TRAIN, CAL, TEST))
    model = GBDT("lightgbm", cc["lightgbm"], list(NAMES_C), cc["seed"] + k)
    model.fit(train_df, train_df["label"].to_numpy())
    cal_raw = model.score(cal)
    # the dangerous point exists only when the cal side can measure it (no granularity limit)
    targets = {"suspicious": 0.01}
    if math.floor(0.001 * int((cal["label"] == 0).sum())) >= ev["min_negatives"]:
        targets["dangerous"] = 0.001
    calib = Calibrator(targets, ev["min_negatives"]).fit(cal["label"].to_numpy(), cal_raw)
    return model, calib, {"train": train_df, "cal": cal, "test": test}


def build_bundle(model: GBDT, calib: Calibrator, frames: dict, lists: Lists, cfg: dict) -> dict:
    thresholds = {"suspicious": None, "dangerous": None} | dict(calib.thresholds)
    targets = cfg["eval"]["target_fprs"]
    test = frames["test"]
    row = evaluate(
        test["label"].to_numpy(),
        model.score(test),
        targets,
        cfg["eval"]["min_negatives"],
        {
            t: thresholds[n]
            for n, t in zip(("suspicious", "dangerous"), targets, strict=True)
            if thresholds[n] is not None
        },
    )
    trees = compact_trees(model.model.booster_)
    return {
        "note": "Generated by `python -m models.tier_c train`. Do not edit by hand.",
        "created": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "model": "tier C: lightgbm on domain / DNS / TLS facts captured at first sight",
        "names": list(NAMES_C),
        "trees": trees,
        "expected_value": expected_value(trees),
        "thresholds": thresholds,
        "isotonic": {"x": calib.iso.X_thresholds_.tolist(), "y": calib.iso.y_thresholds_.tolist()},
        "reasons": reason_rules(list(NAMES_C)),
        "explain": dict(cfg["explain"]),
        "brands": sorted(lists.brands),
        "free_issuers": list(FREE_ISSUERS),
        "train": {
            k: {
                "rows": len(f),
                "phishing": int((f["label"] == 1).sum()),
                "domains": int(f["domain"].nunique()),
            }
            for k, f in frames.items()
        },
        "metrics": {
            k: (None if isinstance(v, float) and math.isnan(v) else v)
            for k, v in row.items()
            if isinstance(v, int | float | bool | type(None))
        },
    }


def model_parity(bundle: dict, model: GBDT, frames: dict, n: int = 60, seed: int = 0) -> dict:
    """Features and probability of test rows, from the fitted model (not the exported trees)."""
    test = frames["test"]
    pick = test.sample(min(n, len(test)), random_state=seed)
    x = pick[list(NAMES_C)].to_numpy(dtype=np.float32)
    probs = model.score(pick)
    walked = 1 / (1 + np.exp(-raw_score(bundle["trees"], x)))
    if np.max(np.abs(walked - probs)) > 1e-9:
        raise AssertionError("exported trees differ from the fitted model")
    return {
        "note": "Generated by `python -m models.tier_c train`. Do not edit by hand.",
        "bundle_created": bundle["created"],
        "cases": [
            {
                "features": clean({n_: float(v) for n_, v in zip(NAMES_C, row, strict=True)}),
                "prob": float(p),
            }
            for row, p in zip(x, probs, strict=True)
        ],
    }


# --- parity fixture for the JavaScript port ---------------------------------------------

FIXTURE_BRANDS = ["paypal", "apple", "microsoft", "amazon", "dhl", "netflix"]
TIME_FORMATS = ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S.000Z", "%Y-%m-%dT%H:%M:%S+00:00")


def _iso(rng: random.Random, t: datetime) -> str:
    return t.strftime(rng.choice(TIME_FORMATS))


def synthetic_cases(n: int = 240, seed: int = 7) -> list[dict]:
    """Varied raw (host record, domain record) pairs: every missing-value path of compute_c."""
    rng = random.Random(seed)
    now = datetime(2026, 10, 27, 12, 0, tzinfo=UTC)
    tlds = ("com", "co.uk", "xyz", "top", "de", "org", "com.br")
    cases = []
    for i in range(n):
        label = i % 2
        stem = rng.choice(["shop", "secure-paypal", "my-apple", "news", "dhl-track", "x"])
        domain = f"{stem}{i}.{rng.choice(tlds)}"
        probe = rng.choice([domain, f"www.{domain}"])
        age = rng.choice([0.2, 3, 20, 200, 3000]) * (0.5 if label else 1)
        registered = datetime.fromtimestamp(now.timestamp() - age * 86400, UTC)
        expires = datetime.fromtimestamp(now.timestamp() + rng.choice([20, 300, 3000]) * 86400, UTC)
        rdap = rng.choice(["ok", "ok", "ok", "not_found", "no_server", "err", "none"])
        dom_rec = {
            "kind": "domain",
            "domain": domain,
            "captured_at": _iso(rng, now),
            "rdap": None,
            "rdap_error": None,
        }
        if rdap == "ok":
            dom_rec["rdap"] = {
                "registered": _iso(rng, registered),
                "expires": _iso(rng, expires) if rng.random() < 0.9 else None,
                "last_changed": _iso(rng, registered) if rng.random() < 0.8 else None,
                "registrar": rng.choice(["Namecheap", "Privacy Service Ltd", None]),
                "status": rng.choice(
                    [
                        [],
                        ["client transfer prohibited"],
                        ["client hold", "add period"],
                        ["serverHold"],
                    ]
                ),
                "nameservers": [],
                "redacted": rng.random() < 0.5,
            }
        elif rdap in ("not_found", "no_server"):
            dom_rec["rdap_error"] = rdap
        elif rdap == "err":
            dom_rec["rdap_error"] = "http_429"
        errors = rng.choice(
            [
                [],
                [],
                [],
                ["MX:TimeoutError"],
                ["TXT:TimeoutError"],
                ["A:TimeoutError"],
                ["NS:TimeoutError"],
                ["CNAME:TimeoutError"],
            ]
        )
        addr = rng.choice([["203.0.113.5"], ["203.0.113.5", "203.0.113.6"], [], ["0.0.0.0"]])
        ns_pool = [f"ns1.{domain}", "a.ns.cloudflare.com", "ns1.hoster.net", "ns2.hoster.net"]
        ns = rng.sample(ns_pool, rng.randint(0, 3))
        dns = rng.choice([None, "x", "x", "x"])
        dns_rec = (
            None
            if dns is None
            else {
                "errors": errors,
                "a": sorted(addr),
                "aaaa": rng.choice([[], ["2001:db8::1"]]),
                "cname": rng.choice([[], [], ["x.cdn.net"]]),
                "ns": sorted(ns),
                "mx_count": rng.choice([0, 1, 2]),
                "spf": rng.random() < 0.5,
                "dmarc": rng.random() < 0.4,
                "min_ttl": rng.choice([None, 30, 300, 3600]),
                "resolves": any(a not in ("0.0.0.0",) for a in addr),
                "sinkhole": bool(addr) and all(a == "0.0.0.0" for a in addr),
            }
        )
        tls_kind = rng.choice(["ok", "ok", "ok", "unverified", "fail", "gaierror", "none"])
        not_before = datetime.fromtimestamp(
            now.timestamp() - rng.choice([0.1, 5, 40, 300]) * 86400, UTC
        )
        not_after = datetime.fromtimestamp(
            not_before.timestamp() + rng.choice([90, 365, 398]) * 86400, UTC
        )
        sans = rng.choice(
            [[probe], [f"*.{domain}", domain], ["paypal-login.example.net", domain], []]
        )
        tls_rec = {
            "ok": {
                "ok": True,
                "verified": True,
                "version": "TLSv1.3",
                "issuer_o": rng.choice(
                    ["Let's Encrypt", "DigiCert Inc", "Google Trust Services", None]
                ),
                "issuer_cn": rng.choice(["R11", "Cloudflare TLS Issuing ECC CA 3", None]),
                "subject_cn": rng.choice([probe, domain, f"*.{domain}", "other.example", None]),
                "not_before": _iso(rng, not_before),
                "not_after": _iso(rng, not_after),
                "san_count": len(sans),
                "sans": sans,
            },
            "unverified": {"ok": True, "verified": False, "error": "self signed certificate"},
            "fail": {"ok": False, "verified": False, "error": "TimeoutError"},
            "gaierror": {"ok": False, "verified": False, "error": "gaierror"},
            "none": None,
        }[tls_kind]
        host_rec = {
            "kind": "host",
            "host": domain,
            "probe_host": probe,
            "domain": domain,
            "label": label,
            "captured_at": _iso(rng, now),
            "dns": dns_rec,
            "tls": tls_rec,
        }
        if rng.random() < 0.2:
            host_rec.pop("probe_host")
        cases.append({"host_rec": host_rec, "domain_rec": dom_rec if rdap != "none" else None})
    return cases


