"""Collect the feature word lists from the internet (run on your PC: ``python -m features lists``).

Every source is fetched with the project's cached HTTP client (timeouts, retries, polite delay)
and written to ``configs/lists/`` or ``configs/platforms.yaml`` with its source and fetch date.
A source that cannot be reached is skipped with a warning and the old file is kept.
Sources are set in ``configs/features.yaml``.
"""

from __future__ import annotations

import json
import logging
import re
import unicodedata
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote

import tldextract
import yaml

from features.lists import LISTS_DIR, MIN_BRAND_LEN, PLATFORMS_FILE
from phishdrift.config import load_config, resolve
from phishdrift.domains import registered_domain
from phishdrift.http import HttpClient

log = logging.getLogger(__name__)
_WORD = re.compile(r"[a-z0-9]+")
_ICANN = tldextract.TLDExtract(
    suffix_list_urls=(), cache_dir=None, include_psl_private_domains=False
)


def _stamp() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d")


def _write_list(name: str, entries: list[str], source: str) -> Path:
    path = LISTS_DIR / name
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"# Source: {source}\n# Fetched: {_stamp()}\n# Entries: {len(entries)}\n"
    path.write_text(header + "\n".join(entries) + "\n", encoding="utf-8")
    return path


def platforms_from_psl(psl_text: str | None = None) -> list[str]:
    """Registrable (public-suffix-only) domains of every PSL *private* suffix.

    ``github.io``, ``web.app``, ``blogspot.com`` ... Without ``psl_text`` the Public Suffix
    List snapshot bundled with tldextract is used (no network)."""
    if psl_text is None:
        ext = tldextract.TLDExtract(
            suffix_list_urls=(), cache_dir=None, include_psl_private_domains=True
        )._get_tld_extractor()
        private = sorted(set(ext.tlds_incl_private) - set(ext.tlds_excl_private))
    else:
        block = psl_text.split("===BEGIN PRIVATE DOMAINS===", 1)[-1]
        private = [
            ln.strip().lstrip("*.!")
            for ln in block.splitlines()
            if ln.strip() and not ln.startswith("//")
        ]
    domains = set()
    for suffix in private:
        parts = _ICANN(f"x.{suffix}")
        if parts.domain and parts.suffix:
            domains.add(f"{parts.domain}.{parts.suffix}")
    return sorted(domains)


def write_platforms(domains: list[str], source: str) -> Path:
    PLATFORMS_FILE.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Hosting platforms: masked behind one neutral token before URL features are computed.\n"
        "# Generated by `python -m features lists`; do not edit by hand (add extras in\n"
        "# configs/features.yaml under `platform_extras`).\n"
        f"# Source: {source}\n# Generated: {_stamp()}\n"
    )
    body = yaml.safe_dump({"platforms": domains}, sort_keys=False, default_flow_style=False)
    PLATFORMS_FILE.write_text(header + body, encoding="utf-8")
    return PLATFORMS_FILE


def _clean_brand(token: str) -> str | None:
    token = unicodedata.normalize("NFKD", token.lower())
    token = "".join(_WORD.findall("".join(c for c in token if not unicodedata.combining(c))))
    return token if len(token) >= MIN_BRAND_LEN else None


WIKIDATA_TIMEOUT_S = 180


def brands_from_wikidata(client: HttpClient, cfg: dict) -> list[str]:
    """Brand tokens from Wikidata: companies and organisations with an official website
    and many language editions (a proxy for being widely known, not a popularity rank).
    The token is the registrable domain label of the official site and the English name."""
    rows: list[dict] = []
    failed = 0
    for qid in cfg["wikidata_types"]:
        sparql = cfg["wikidata_query"].format(type=qid, min_sitelinks=cfg["wikidata_min_sitelinks"])
        url = f"https://query.wikidata.org/sparql?format=json&query={quote(sparql)}"
        try:
            body = client.get(
                url,
                cache_ttl_s=7 * 86400,
                headers={"Accept": "application/sparql-results+json"},
                timeout_s=WIKIDATA_TIMEOUT_S,
            )
            rows += json.loads(body)["results"]["bindings"]
        except Exception as exc:  # noqa: BLE001 - one type failing must not lose the others
            failed += 1
            log.warning("Wikidata type %s skipped: %s", qid, str(exc)[:200])
    if failed == len(cfg["wikidata_types"]):
        raise RuntimeError("every Wikidata query failed")
    brands: set[str] = set()
    for r in rows:
        site = r.get("site", {}).get("value", "")
        label = r.get("label", {}).get("value", "")
        host_label = _ICANN(site).domain if site else ""
        for tok in (host_label, label):
            cleaned = _clean_brand(tok)
            if cleaned:
                brands.add(cleaned)
    return sorted(brands)


def read_brand_file(path: Path) -> list[str]:
    """Brands from a reviewed file in the repo: one per line, ``#`` starts a comment."""
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        token = line.split("#", 1)[0].strip()
        if token and (cleaned := _clean_brand(token)):
            out.append(cleaned)
    return out


def apply_brand_files(brands: set[str], files: list[Path], exclude: list[str]) -> set[str]:
    """Add the reviewed brand files, then drop the reviewed generic words (``brand_exclude``).
    Exclusions win, so a removed word cannot come back from Wikidata on the next run."""
    for path in files:
        brands = brands | set(read_brand_file(path))
    return brands - {_clean_brand(w) or w for w in exclude}


def lines_from_url(client: HttpClient, url: str) -> list[str]:
    text = client.get(url, cache_ttl_s=7 * 86400).decode("utf-8", errors="replace")
    return [ln.strip().lower() for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]


def run(only: list[str] | None = None) -> dict[str, int]:
    cfg = load_config("features")["lists"]
    client = HttpClient.from_config(
        load_config("collector")["http"],
        resolve(load_config("collector")["paths"]["http_cache_dir"]),
    )
    done: dict[str, int] = {}

    def wanted(name: str) -> bool:
        return not only or name in only

    if wanted("platforms"):
        domains = set(platforms_from_psl())
        try:
            text = client.get(cfg["psl_url"], cache_ttl_s=7 * 86400).decode("utf-8")
            domains |= set(platforms_from_psl(text))
            source = cfg["psl_url"]
        except Exception as exc:  # noqa: BLE001 - offline: the bundled snapshot is enough
            log.warning("PSL download failed (%s); using the tldextract snapshot", exc)
            source = "Public Suffix List snapshot bundled with tldextract"
        for url in cfg.get("platform_extra_urls", []):
            try:
                domains |= {registered_domain(d) or d for d in lines_from_url(client, url)}
            except Exception as exc:  # noqa: BLE001
                log.warning("skipped %s: %s", url, exc)
        domains |= {d.lower() for d in cfg.get("platform_extras", [])}
        write_platforms(sorted(domains), source)
        done["platforms"] = len(domains)

    if wanted("brands"):
        brands: set[str] = {_clean_brand(b) or "" for b in cfg.get("brand_seed", [])}
        try:
            brands |= set(brands_from_wikidata(client, cfg))
        except Exception as exc:  # noqa: BLE001
            log.warning("Wikidata brands skipped: %s", exc)
        for url in cfg.get("brand_urls", []):
            try:
                brands |= {b for b in map(_clean_brand, lines_from_url(client, url)) if b}
            except Exception as exc:  # noqa: BLE001
                log.warning("skipped %s: %s", url, exc)
        brands.discard("")
        brands = apply_brand_files(
            brands,
            [resolve(f) for f in cfg.get("brand_files", [])],
            cfg.get("brand_exclude", []),
        )
        _write_list(
            "brands.txt",
            sorted(brands),
            "brand_seed + Wikidata + brand_urls + brand_files - brand_exclude"
            " (configs/features.yaml)",
        )
        done["brands"] = len(brands)

    for name, key in (("shorteners", "shortener_urls"), ("keywords", "keyword_urls")):
        if not wanted(name):
            continue
        entries = {e.lower() for e in cfg.get(f"{name}_seed", [])}
        for url in cfg.get(key, []):
            try:
                entries |= set(lines_from_url(client, url))
            except Exception as exc:  # noqa: BLE001
                log.warning("skipped %s: %s", url, exc)
        _write_list(f"{name}.txt", sorted(entries), f"{name}_seed + {key} (configs/features.yaml)")
        done[name] = len(entries)
    return done
