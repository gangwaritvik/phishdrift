def _pick(rng: random.Random, seq, k: int) -> list:
    return [seq[rng.randrange(len(seq))] for _ in range(k)]


def _text(rng: random.Random, n_words: int, unicode_p: float = 0.1) -> str:
    out = []
    for _ in range(n_words):
        if rng.random() < unicode_p:
            out.append(rng.choice(UNICODE_BITS))
        else:
            out.append(rng.choice(WORDS))
    return " ".join(out)


