def _ranges(pred) -> list[list[int]]:
    out: list[list[int]] = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF or not pred(chr(cp)):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def parser_fingerprint() -> str:
    """Hash of the CPython ``html.parser`` and ``html`` sources the values come from."""
    h = hashlib.sha256()
    for mod in (html.parser, html):
        h.update(inspect.getsource(mod).encode("utf-8"))
    return h.hexdigest()[:16]


def pydata_source() -> str:
    from html import _invalid_charrefs, _invalid_codepoints  # noqa: PLC2701

    space = re.compile(r"\s")
    word = re.compile(r"\w")
    data = {
        "HTML5": html.entities.html5,
        "INVALID_CHARREFS": {str(k): v for k, v in sorted(_invalid_charrefs.items())},
        "INVALID_CODEPOINTS": sorted(_invalid_codepoints),
        "SPACE_RANGES": _ranges(lambda c: space.fullmatch(c) is not None),
        "WORD_RANGES": _ranges(lambda c: word.fullmatch(c) is not None),
        "UNASSIGNED_RANGES": _ranges(lambda c: unicodedata.category(c) == "Cn"),
    }
    lines = [
        "// Generated by `python -m features export-js` (features/html_parity.py). Do not edit.",
        f"// CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        f'export const UNICODE_VERSION = "{unicodedata.unidata_version}";',
    ]
    for name, value in data.items():
        lines.append(f"export const {name} = {json.dumps(value, ensure_ascii=True)};")
    return "\n".join(lines) + "\n"


def export_pydata(path: Path = PYDATA_FILE) -> Path:
    path.write_text(pydata_source(), encoding="utf-8")
    return path


