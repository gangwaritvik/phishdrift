def parity_pages() -> list[tuple[str, object]]:
    rng = random.Random(20261013)
    pages = _handwritten()
    pages += [_random_page(rng, i) for i in range(160)]
    return pages


def build_html(spec) -> str:
    return spec if isinstance(spec, str) else "".join(piece * n for piece, n in spec)


def _clean(v: float) -> float | None:
    return None if math.isnan(v) else v


def parity_fixture_b() -> dict:
    cases = []
    for url, spec in parity_pages():
        values, status = analyze(url, build_html(spec), lists=FIXTURE_LISTS_B)
        row = [None] * len(NAMES_B) if values is None else [_clean(values[k]) for k in NAMES_B]
        cases.append({"url": url, "html": spec, "status": status, "values": row})
    return {
        "note": "Generated by `python -m features parity` (features/html_parity.py). Do not edit.",
        "python": sys.version.split()[0],
        "parser": parser_fingerprint(),
        "names": list(NAMES_B),
        "lists": lists_payload(FIXTURE_LISTS_B, FIXTURE_FITTED),
        "cases": cases,
    }


def write_parity_b(path: Path = PARITY_FILE_B) -> Path:
    """One case per line, so a changed feature shows up as a readable diff."""
    data = parity_fixture_b()

    def dump(x) -> str:
        return json.dumps(x, ensure_ascii=False, sort_keys=True)

    keys = ("note", "python", "parser", "names", "lists")
    lines = ["{"]
    lines += [f' "{k}": {dump(data[k])},' for k in keys]
    lines.append(' "cases": [')
    lines.append(",\n".join(f"  {dump(c)}" for c in data["cases"]))
    lines += [" ]", "}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
