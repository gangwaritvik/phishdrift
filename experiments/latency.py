"""Latency of the in-browser tier A model: ``python -m experiments.latency [--runs N]``.

Runs ``js/bench/latency.mjs`` (Node/V8, the engine Chrome uses) over the 272 URLs of
``tests/fixtures/hybrid_parity.json`` and writes ``reports/latency.md`` and
``reports/tables/latency.csv``. Timings depend on the machine; the report records Node's version
and the CPU count. Backend response times are not measured here (they are dominated by RDAP, DNS
and TLS lookups on the network and are cached per domain).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
from pathlib import Path

import pandas as pd

BENCH = Path(__file__).resolve().parents[1] / "js" / "bench" / "latency.mjs"


def measure(runs: int) -> dict:
    out = subprocess.run(
        ["node", str(BENCH), "--runs", str(runs)], capture_output=True, text=True, check=True
    )
    return json.loads(out.stdout)


def render(r: dict) -> str:
    rows = [
        ("score one URL (features, text models, trees)", r["score"]),
        ("score one URL and explain it (TreeSHAP reasons)", r["score_with_reasons"]),
    ]
    lines = [
        "# Latency of the in-browser model",
        "",
        "Generated by `python -m experiments.latency`. Do not edit by hand.",
        f"Node {r['node']} (V8), {os.cpu_count()} CPUs, {r['urls']} URLs x {r['runs']} runs each "
        "(`tests/fixtures/hybrid_parity.json`), single thread, after a warm-up.",
        "",
        "| step | median | 95th percentile | max |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {name} | {s['median_ms']:.1f} ms | {s['p95_ms']:.1f} ms | {s['max_ms']:.1f} ms |"
        for name, s in rows
    ]
    lines += [
        "",
        f"Start-up, once per browser session: parse the {r['bundle_mb']:.1f} MB model bundle "
        f"{r['json_parse_ms']:.0f} ms, build the model {r['model_build_ms']:.0f} ms.",
        "The extension scores every navigation without reasons and asks for reasons only when a "
        "warning is shown.",
        "",
    ]
    return "\n".join(lines)


def run(reports: Path, runs: int) -> Path:
    r = measure(runs)
    tables = reports / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(
        [
            {"step": name, "urls": r["urls"], "runs": r["runs"]} | s
            for name, s in (("score", r["score"]), ("score_with_reasons", r["score_with_reasons"]))
        ]
    ).to_csv(tables / "latency.csv", index=False)
    out = reports / "latency.md"
    out.write_text(render(r), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.latency")
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--runs", type=int, default=5)
    a = ap.parse_args(argv)
    print(run(a.reports, a.runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
