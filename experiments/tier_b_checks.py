"""Leakage checks for the tier B (URL + HTML) result, which sits above 0.99 ROC-AUC on HTML rows.

python -m experiments.tier_b_checks [--processed data/processed] [--reports reports] [--splits ...]

Per domain-grouped split, on the same rows as ``experiments.tier_b`` (rows with usable HTML):

- ``ab_lgbm``            LightGBM on tier A + tier B features (the model being checked);
- ``ab_lgbm_shuffled``   the same, trained on labels permuted within the train side, unweighted
  (flag rule: |mean test ROC-AUC - 0.5| > ``eval.shuffled_label_flag``);
- ``b_only``             LightGBM on the 84 HTML features alone, to show how much the page says
  without the address;
- ``ab_lgbm`` on test rows with no exact twin in train: a test row is a twin when its tier B
  feature vector (rounded to 6 digits) also occurs in the train side. The near-duplicate HTML
  filter of the corpus build works on page text; this checks the feature space the model sees.

One result file per split (``tables/tier_b_checks/split_<k>.csv``) so splits can run in parallel.
Writes ``tier_b_checks.md``.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from data_pipeline.split import CAL, TEST, TRAIN
from experiments.tier_a import apply_fitted, assert_no_overlap, refit
from experiments.tier_b import load_b
from features.lists import load_lists
from features.registry import NAMES, NAMES_B
from models.gbdt import GBDT
from phishdrift.config import load_config

log = logging.getLogger("tier_b_checks")
ROUND = 6


def _auc(y, s) -> float:
    return float(roc_auc_score(y, s)) if len(set(y)) == 2 else float("nan")


def _key(frame: pd.DataFrame) -> pd.Series:
    return pd.Series(
        list(map(tuple, frame[list(NAMES_B)].round(ROUND).fillna(-1e9).to_numpy())),
        index=frame.index,
    )


def run_split(k, pool, splits, time_slice, lists, cfg) -> list[dict]:
    side = splits[f"split_{k}"].to_numpy()
    train, cal, test = (pool[side == s] for s in (TRAIN, CAL, TEST))
    assert_no_overlap(train, test, "train", "test")
    fitted = refit(train, lists)
    train, test = apply_fitted(train, fitted), apply_fitted(test, fitted)
    sets = {"test": test}
    if time_slice is not None:
        sets["time_slice"] = apply_fitted(time_slice, fitted)
    y, w = train["label"].to_numpy(), train["weight"].to_numpy()
    both, only_b = list(NAMES) + list(NAMES_B), list(NAMES_B)
    rows = []

    def add(model, eval_set, frame, score, **extra):
        rows.append(
            {"split": k, "model": model, "eval_set": eval_set, "n_urls": len(frame)}
            | {"n_domains": frame["domain"].nunique(), "roc_auc": _auc(frame["label"], score)}
            | extra
        )

    main_model = GBDT("lightgbm", cfg["lightgbm"], both, cfg["seed"]).fit(train, y, w)
    twin = _key(test).isin(set(_key(train))).to_numpy()
    s_test = main_model.score(test)
    for name, frame in sets.items():
        add("ab_lgbm", name, frame, main_model.score(frame))
    add("ab_lgbm", "test:no_twin", test[~twin], s_test[~twin], n_twins=int(twin.sum()))
    shuffled = np.random.default_rng(cfg["seed"] + k).permutation(y)
    control = GBDT("lightgbm", cfg["lightgbm"], both, cfg["seed"]).fit(train, shuffled)
    for name, frame in sets.items():
        add("ab_lgbm_shuffled", name, frame, control.score(frame))
    b_model = GBDT("lightgbm", cfg["lightgbm"], only_b, cfg["seed"]).fit(train, y, w)
    for name, frame in sets.items():
        add("b_only", name, frame, b_model.score(frame))
    log.info("split %d done (%d twins of %d test rows)", k, int(twin.sum()), len(test))
    return rows


def render(runs: pd.DataFrame, cfg: dict) -> str:
    flag = cfg["eval"]["shuffled_label_flag"]

    def spread(g):
        v = g["roc_auc"].dropna()
        return f"{v.median():.4f} [{v.min():.4f}, {v.max():.4f}]"

    lines = [
        "# Tier B leakage checks",
        "",
        "Generated by `python -m experiments.tier_b_checks`. Do not edit by hand.",
        "Rows with usable HTML only (the rows of `reports/tier_b.md`). ROC-AUC, median "
        "[min, max] over splits.",
        "",
        "| model | eval set | splits | URLs (median) | domains (median) | ROC-AUC |",
        "|---|---|---|---|---|---|",
    ]
    for (model, eval_set), g in runs.groupby(["model", "eval_set"], sort=False):
        lines.append(
            f"| {model} | {eval_set} | {g['split'].nunique()} | {int(g['n_urls'].median()):,} "
            f"| {int(g['n_domains'].median()):,} | {spread(g)} |"
        )
    twins = runs.loc[runs["eval_set"] == "test:no_twin", "n_twins"]
    full = runs[(runs["model"] == "ab_lgbm") & (runs["eval_set"] == "test")]["n_urls"]
    if len(twins):
        lines += [
            "",
            f"Exact twins (a test row whose 84 HTML feature values equal a train row's): median "
            f"{int(twins.median()):,} of {int(full.median()):,} test rows "
            f"({100 * twins.median() / full.median():.2f}%).",
        ]
    ctrl = runs[(runs["model"] == "ab_lgbm_shuffled") & (runs["eval_set"] == "test")]
    if len(ctrl):
        m = ctrl["roc_auc"].mean()
        verdict = "FLAGGED" if abs(m - 0.5) > flag else "not flagged"
        lines += [
            "",
            f"Shuffled-label control (labels permuted within train, no sample weights): mean test "
            f"ROC-AUC {m:.4f} over {len(ctrl)} splits; {verdict} (flag rule: |mean - 0.5| > "
            f"{flag}).",
        ]
    lines.append("")
    return "\n".join(lines)


def write_reports(reports: Path, cfg: dict) -> Path:
    files = sorted((reports / "tables" / "tier_b_checks").glob("split_*.csv"))
    runs = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    runs.to_csv(reports / "tables" / "tier_b_checks_runs.csv", index=False)
    out = reports / "tier_b_checks.md"
    out.write_text(render(runs, cfg), encoding="utf-8")
    return out


def run(processed: Path, reports: Path, split_ids=None, cfg=None, lists=None) -> Path:
    cfg = cfg or load_config("models")
    lists = lists or load_lists()
    out_dir = reports / "tables" / "tier_b_checks"
    out_dir.mkdir(parents=True, exist_ok=True)
    pool = load_b(processed, "pool", lists)
    if pool is None:
        raise SystemExit("features_b.parquet not found in the processed folder")
    time_slice = load_b(processed, "time_slice", lists)
    splits = pd.read_parquet(processed / "splits.parquet")
    splits = pool[["uid"]].merge(splits, on="uid", how="left", validate="one_to_one")
    n_splits = sum(c.startswith("split_") for c in splits.columns)
    for k in split_ids if split_ids is not None else range(n_splits):
        out = out_dir / f"split_{k}.csv"
        if out.exists():
            continue
        rows = run_split(k, pool, splits, time_slice, lists, cfg)
        tmp = out.with_suffix(".tmp")
        pd.DataFrame(rows).to_csv(tmp, index=False)
        tmp.replace(out)
    return write_reports(reports, cfg)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.tier_b_checks")
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--splits", type=int, nargs="*", default=None)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--lists-dir", default=None)
    ap.add_argument("--platforms-file", default=None)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    if a.report_only:
        print(write_reports(a.reports, load_config("models")))
        return 0
    lists = load_lists(a.lists_dir, a.platforms_file)
    print(run(a.processed, a.reports, a.splits, lists=lists))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
