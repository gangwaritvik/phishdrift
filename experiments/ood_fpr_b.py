"""Out-of-distribution false-positive rate of the tier B models (URL + HTML).

python -m experiments.ood_fpr_b --ood-html-dir data/raw/ood_html [--processed ...] [--splits ...]

Same idea as ``experiments.ood_fpr`` but on the pages of ``python -m collector crawl-ood
--html-pass`` (stored HTML), scored with the models that read the page. Only pages with usable
HTML are scored (the content script runs no page checks on the others); their share is reported.
Thresholds for target FPR 1% and 0.1% come from the cal side of the pool rows that have HTML.
One result file per split in ``tables/ood_fpr_b_runs`` (parallel-safe); ``ood_fpr_b.md`` is
rebuilt from them.
"""

from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import numpy as np
import pandas as pd

from collector.ood import load_pages
from data_pipeline.split import CAL, TRAIN
from experiments.metrics import operating_point
from experiments.tier_a import _fmt, apply_fitted, assert_no_overlap, refit
from experiments.tier_b import _model, load_b
from features.extract import extract
from features.fit import Fitted
from features.lists import Lists, load_lists
from features.registry import NAMES, NAMES_B
from features.urlparts import parse
from phishdrift.config import load_config
from phishdrift.domains import url_depth, url_key

log = logging.getLogger("ood_fpr_b")

VARIANTS = ("a_hybrid2", "ab_lgbm", "ab_hybrid2")


def load_ood_b(html_dir: Path, lists: Lists) -> tuple[pd.DataFrame, dict]:
    """Pages with usable HTML and their tier A + B features; plus counts for the report."""
    pages = load_pages(html_dir)
    pages = pages[pages["html"].notna()].drop_duplicates("url")
    rows = [
        extract(u, h, lists=lists, fitted=Fitted())
        for u, h in zip(pages["url"], pages["html"], strict=True)
    ]
    feats = pd.DataFrame(rows, columns=[*NAMES, *NAMES_B]).astype("float32")
    usable = feats[list(NAMES_B)].notna().any(axis=1).to_numpy()
    stats = {"pages": len(pages), "usable": int(usable.sum())}
    df = feats[usable].reset_index(drop=True)
    kept = pages[usable].reset_index(drop=True)
    df["url"] = kept["url"].to_numpy()
    df["domain"] = kept["domain"].astype(str).str.lower().to_numpy()
    df["label"] = 0
    df["depth"] = [url_depth(u) for u in df["url"]]
    df["_parts"] = [parse(u, lists.platforms) for u in df["url"]]
    df["_text"] = [p.canon if p is not None else "" for p in df["_parts"]]
    df["_key"] = df["url"].map(url_key)
    return df, stats


def run_split(k, pool, splits, ood, lists, cfg) -> list[dict]:
    targets, min_neg = cfg["eval"]["target_fprs"], cfg["eval"]["min_negatives"]
    side = splits[f"split_{k}"].to_numpy()
    train, cal = (pool[side == s] for s in (TRAIN, CAL))
    assert_no_overlap(train, ood, "train", "ood")
    assert_no_overlap(cal, ood, "cal", "ood")
    fitted = refit(train, lists)
    train, cal = (apply_fitted(f, fitted) for f in (train, cal))
    ood_k = apply_fitted(ood, fitted)
    rows = []
    for variant in VARIANTS:
        t0 = time.monotonic()
        model = _model(variant, cfg, train, train["label"].to_numpy(), train["weight"].to_numpy())
        s_cal, s_ood = model.score(cal), model.score(ood_k)
        for t in targets:
            thr = operating_point(cal["label"], s_cal, t, min_neg)["threshold"]
            rows.append(
                {
                    "split": k,
                    "model": variant,
                    "target_fpr": t,
                    "threshold": thr,
                    "n_urls": len(ood_k),
                    "n_domains": ood_k["domain"].nunique(),
                    "ood_fpr": float(np.mean(s_ood >= thr)),
                }
            )
        log.info("split %d %s: %.0fs", k, variant, time.monotonic() - t0)
    return rows


def render(runs: pd.DataFrame, stats: dict) -> str:
    first = runs.iloc[0]
    lines = [
        "# Out-of-distribution false-positive rate of the page-based (tier B) models",
        "",
        "Generated by `python -m experiments.ood_fpr_b`. Do not edit by hand.",
        f"{int(first['n_urls']):,} naturally browsed legitimate pages with usable HTML from",
        f"{int(first['n_domains']):,} sites ({stats['usable']:,} of {stats['pages']:,} fetched",
        "pages had usable HTML; the others get no page checks). Share scored as phishing at the",
        "cal-side",
        "threshold for the target FPR. Median over splits [min, max].",
        "",
        "| model | target FPR | splits | OOD FPR |",
        "|---|---|---|---|",
    ]
    for (model, t), g in runs.groupby(["model", "target_fpr"], sort=False):
        v = g["ood_fpr"]
        spread = f"{_fmt(v.median())} [{_fmt(v.min())}, {_fmt(v.max())}]"
        lines.append(f"| {model} | {t:.1%} | {len(g)} | {spread} |")
    return "\n".join(lines + [""])


def write_reports(reports: Path, stats: dict) -> Path:
    parts = sorted((reports / "tables" / "ood_fpr_b_runs").glob("split_*.csv"))
    runs = pd.concat([pd.read_csv(p) for p in parts], ignore_index=True)
    runs.to_csv(reports / "tables" / "ood_fpr_b_runs.csv", index=False)
    out = reports / "ood_fpr_b.md"
    out.write_text(render(runs, stats), encoding="utf-8")
    return out


def run(processed, reports, html_dir, split_ids=None, cfg=None, lists=None) -> Path:
    cfg = cfg or load_config("models")
    lists = lists or load_lists()
    per_split = reports / "tables" / "ood_fpr_b_runs"
    per_split.mkdir(parents=True, exist_ok=True)
    pool = load_b(processed, "pool", lists)
    if pool is None:
        raise SystemExit("features_b.parquet not found in the processed folder")
    splits = pd.read_parquet(processed / "splits.parquet")
    splits = pool[["uid"]].merge(splits, on="uid", how="left", validate="one_to_one")
    ood, stats = load_ood_b(html_dir, lists)
    log.info("ood pages: %s, domains %d", stats, ood["domain"].nunique())
    n_splits = sum(c.startswith("split_") for c in splits.columns)
    for k in split_ids if split_ids is not None else range(n_splits):
        out = per_split / f"split_{k}.csv"
        if out.exists():
            continue
        rows = run_split(k, pool, splits, ood, lists, cfg)
        tmp = out.with_suffix(".tmp")
        pd.DataFrame(rows).to_csv(tmp, index=False)
        tmp.replace(out)
        write_reports(reports, stats)
        log.info("split %d written", k)
    return write_reports(reports, stats)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.ood_fpr_b")
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--ood-html-dir", type=Path, default=Path("data/raw/ood_html"))
    ap.add_argument("--splits", type=int, nargs="*", default=None)
    ap.add_argument("--lists-dir", default=None)
    ap.add_argument("--platforms-file", default=None)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    lists = load_lists(a.lists_dir, a.platforms_file)
    print(run(a.processed, a.reports, a.ood_html_dir, a.splits, lists=lists))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
