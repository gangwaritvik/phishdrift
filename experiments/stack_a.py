"""Stacked and calibrated tier A model over the domain-grouped splits (milestone 5, tier A).

python -m experiments.stack_a [--processed data/processed] [--reports reports] [--splits ...]

Per split k: LightGBM, XGBoost and the char n-gram model give out-of-fold scores on split k's
train side (domain-grouped folds, fitted features refitted per fold); a logistic-regression meta
model combines them. Isotonic calibration and the verdict thresholds ("suspicious" at FPR 1%,
"dangerous" at FPR 0.1%) come from the cal side only. Metrics on test, the held-out source and
the time slice use those thresholds, plus Brier score and calibration error of the calibrated
probability.

Writes ``tables/stack_a_runs.csv`` and ``stack_a.md``; finished splits are skipped on a rerun.
"""

from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import numpy as np
import pandas as pd

from data_pipeline.split import CAL, TEST, TRAIN
from experiments.metrics import evaluate
from experiments.tier_a import (
    PARTS,
    Spec,
    _append,
    _fmt,
    apply_fitted,
    assert_no_overlap,
    load_part,
    make_model,
    model_input,
    refit,
)
from features.lists import Lists, load_lists
from models.calibrate import Calibrator, brier, expected_calibration_error
from models.stack import Stack
from phishdrift.config import load_config

log = logging.getLogger("stack_a")
BASES = (Spec("lightgbm", "all"), Spec("xgboost", "all"), Spec("char_ngram", "url_text"))


def make_stack(lists: Lists, cfg: dict) -> Stack:
    def refit_frames(train: pd.DataFrame, frames: list[pd.DataFrame]) -> list[pd.DataFrame]:
        fitted = refit(train, lists)
        return [apply_fitted(f, fitted) for f in frames]

    bases = {s.name: (lambda s=s: make_model(s, cfg)) for s in BASES}
    inputs = {s.name: (lambda frame, s=s: model_input(s, frame)) for s in BASES}
    sc = cfg["stack"]
    return Stack(bases, inputs, refit_frames, sc["n_folds"], cfg["seed"], sc["meta_c"])


def run_split(
    k: int, pool: pd.DataFrame, splits: pd.DataFrame, holdouts: dict, lists: Lists, cfg: dict
) -> list[dict]:
    ev = cfg["eval"]
    targets, min_neg = ev["target_fprs"], ev["min_negatives"]
    side = splits[f"split_{k}"].to_numpy()
    train, cal, test = (pool[side == s] for s in (TRAIN, CAL, TEST))
    for name, other in {"cal": cal, "test": test, **holdouts}.items():
        assert_no_overlap(train, other, "train", name)

    t0 = time.monotonic()
    stack = make_stack(lists, cfg).fit(train, train["weight"].to_numpy())
    fitted = refit(train, lists)
    cal, test = apply_fitted(cal, fitted), apply_fitted(test, fitted)
    holdouts = {n: apply_fitted(h, fitted) for n, h in holdouts.items()}

    verdicts = {"suspicious": targets[0], "dangerous": targets[1]}
    calib = Calibrator(verdicts, min_neg).fit(cal["label"].to_numpy(), stack.score(cal))
    thresholds = {
        targets[0]: calib.thresholds["suspicious"],
        targets[1]: calib.thresholds["dangerous"],
    }
    rows = []
    base = {"split": k, "model": "stack", "features": "+".join(s.name for s in BASES)}
    weights = {f"meta_{n}": v for n, v in stack.meta_weights.items()}
    for set_name, frame in {"test": test, **holdouts}.items():
        y = frame["label"].to_numpy()
        raw = stack.score(frame)
        prob = calib.probability(raw)
        verdict = calib.verdict(raw)
        row = evaluate(y, raw, targets, min_neg, thresholds)
        row |= {
            "brier": brier(y, prob),
            "ece": expected_calibration_error(y, prob),
            "share_suspicious": float((verdict == 1).mean()),
            "share_dangerous": float((verdict == 2).mean()),
            "threshold_suspicious": calib.thresholds["suspicious"],
            "threshold_dangerous": calib.thresholds["dangerous"],
            "prob_at_suspicious": float(calib.probability(np.array([thresholds[targets[0]]]))[0]),
            "prob_at_dangerous": float(calib.probability(np.array([thresholds[targets[1]]]))[0]),
        }
        n_dom = frame["domain"].nunique()
        rows.append(base | {"eval_set": set_name, "n_domains": n_dom} | row | weights)
    log.info("split %d stack: %.0fs", k, time.monotonic() - t0)
    return rows


def render(runs: pd.DataFrame, cfg: dict) -> str:
    lines = [
        "# Stacked tier A model (URL only), calibrated",
        "",
        "Generated by `python -m experiments.stack_a`. Do not edit by hand.",
        "Out-of-fold LightGBM, XGBoost and char n-gram scores combined by logistic regression;",
        "thresholds and isotonic calibration from each split's cal side. Median over splits",
        "[min, max]. `cal` columns: the suspicious (1% FPR) and dangerous (0.1% FPR) thresholds",
        "applied to the set.",
        "",
        "| set | splits | URLs | domains | ROC-AUC | recall @1% FPR | recall @0.1% FPR "
        "| suspicious: recall / FPR | dangerous: recall / FPR | Brier | ECE |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for set_name, g in runs.groupby("eval_set", sort=False):

        def cell(m: str, pct: bool = True, g=g) -> str:
            return f"{_fmt(g[m].median(), pct)} [{_fmt(g[m].min(), pct)}, {_fmt(g[m].max(), pct)}]"

        lines.append(
            f"| {set_name} | {len(g)} | {int(g['n_urls'].median()):,} "
            f"| {int(g['n_domains'].median()):,} | {cell('roc_auc', False)} "
            f"| {cell('op_1pct_recall')} | {cell('op_0p1pct_recall')} "
            f"| {_fmt(g['cal_1pct_recall'].median())} / {_fmt(g['cal_1pct_fpr'].median())} "
            f"| {_fmt(g['cal_0p1pct_recall'].median())} / {_fmt(g['cal_0p1pct_fpr'].median())} "
            f"| {g['brier'].median():.4f} | {g['ece'].median():.4f} |"
        )
    meta = [c for c in runs if c.startswith("meta_")]
    test = runs[runs["eval_set"] == "test"]
    lines += [
        "",
        "Meta-model weights (median over splits; inputs are base-learner log-odds): "
        + ", ".join(f"{c[5:]} {test[c].median():.3f}" for c in meta)
        + ".",
        "",
    ]
    trip = cfg["eval"]["leakage_tripwire"]
    hot = runs[(runs["eval_set"] != "test") & (runs["roc_auc"] > trip)]
    if not hot.empty:
        lines += [f"**Leakage tripwire:** holdout ROC-AUC above {trip:.0%}. Investigate.", ""]
    return "\n".join(lines)


def run(
    processed: Path,
    reports: Path,
    split_ids: list[int] | None = None,
    cfg: dict | None = None,
    lists: Lists | None = None,
) -> Path:
    cfg = cfg or load_config("models")
    lists = lists or load_lists()
    tables = reports / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    out = tables / "stack_a_runs.csv"
    done = set(pd.read_csv(out)["split"]) if out.exists() else set()
    frames = {p: load_part(processed, p, lists) for p in PARTS}
    pool = frames.pop("pool")
    splits = pd.read_parquet(processed / "splits.parquet")
    splits = pool[["uid"]].merge(splits, on="uid", how="left", validate="one_to_one")
    n_splits = sum(c.startswith("split_") for c in splits.columns)
    for k in split_ids if split_ids is not None else range(n_splits):
        if k in done:
            continue
        _append(out, run_split(k, pool, splits, frames, lists, cfg))
        (reports / "stack_a.md").write_text(render(pd.read_csv(out), cfg), encoding="utf-8")
        log.info("split %d written", k)
    return reports / "stack_a.md"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.stack_a")
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--splits", type=int, nargs="*", default=None)
    ap.add_argument("--lists-dir", default=None)
    ap.add_argument("--platforms-file", default=None)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    lists = load_lists(a.lists_dir, a.platforms_file)
    print(run(a.processed, a.reports, a.splits, lists=lists))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
