"""Size, latency and Python/JavaScript parity of two exported address bundles (E0 and E2).

python -m experiments.lookalike_cost --e0 BUNDLE PARITY --e2 BUNDLE PARITY [--out DIR]

Each bundle is exported by ``python -m models.export_hybrid`` (E2 with ``--lookalike``) into a
scratch folder; this only reads them and runs ``js/bench/latency.mjs`` (Node/V8) on each with its
own parity file. Timings depend on the machine; both are measured on it, back to back.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from experiments.latency import measure


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.lookalike_cost")
    ap.add_argument("--e0", nargs=2, type=Path, required=True, metavar=("BUNDLE", "PARITY"))
    ap.add_argument("--e2", nargs=2, type=Path, required=True, metavar=("BUNDLE", "PARITY"))
    ap.add_argument("--runs", type=int, default=5)
    ap.add_argument("--out", type=Path, default=Path("reports/lookalike_e2"))
    a = ap.parse_args(argv)
    res = {n: measure(a.runs, *getattr(a, n)) for n in ("e0", "e2")}
    lines = [
        "# Size, latency and parity of the E0 and E2 address bundles",
        "",
        "Generated by `python -m experiments.lookalike_cost`. Do not edit by hand.",
        f"Node {res['e0']['node']} (V8), {os.cpu_count()} CPUs, {res['e0']['urls']} parity URLs x "
        f"{a.runs} runs each, one thread. Parity = JavaScript's probability against Python's for "
        "the same bundle (largest absolute difference) and how many URLs give other reasons.",
        "",
        "| bundle | size MB | score (median / p95 ms) | score + reasons (median / p95 ms) "
        "| parse + build ms | parity max diff | reason mismatches |",
        "|---|---|---|---|---|---|---|",
    ]
    for n, r in res.items():
        lines.append(
            f"| {n.upper()} | {r['bundle_mb']:.2f} | {r['score']['median_ms']:.2f} / "
            f"{r['score']['p95_ms']:.2f} | {r['score_with_reasons']['median_ms']:.1f} / "
            f"{r['score_with_reasons']['p95_ms']:.1f} | "
            f"{r['json_parse_ms'] + r['model_build_ms']:.0f} "
            f"| {r['parity_max_abs_diff']:.1e} | {r['parity_reason_mismatches']} of "
            f"{r['parity_cases']} |"
        )
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "cost.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
