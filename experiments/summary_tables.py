"""Summary tables the report needs, built only from the per-split run tables in ``reports/tables``.

1. Precision, F1, recall and FPR at the calibration-side thresholds (1% and 0.1% FPR targets) for
   every model and evaluation set: what a deployed model would do.
2. Depth-matched results for tier A (from ``tier_a_depth.csv``): recall at fixed FPR inside each
   URL-depth bucket of the test side, so depth cannot stand in for the label.

No model is trained here. Writes ``tables/summary_cal.csv``, ``tables/summary_depth.csv`` and
``summary.md``. Usage: ``python -m experiments.summary_tables [--reports reports]``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

# run table -> how its rows are named in the summary
RUN_TABLES = {
    "tier_a_runs.csv": "tier A",
    "hybrid_a_runs.csv": "hybrid",
    "hybrid2_runs.csv": "hybrid2",
    "stack_a_runs.csv": "stack",
    "tier_b_runs.csv": "tier B",
    "blend_runs.csv": "blend",
}
EVAL_SETS = ["test", "heldout_source", "time_slice", "test:html", "test_normalised"]
CAL_COLS = {
    "cal_1pct_recall": "cal 1% recall",
    "cal_1pct_fpr": "cal 1% FPR",
    "cal_1pct_precision": "cal 1% precision",
    "cal_1pct_f1": "cal 1% F1",
    "cal_0p1pct_recall": "cal 0.1% recall",
    "cal_0p1pct_fpr": "cal 0.1% FPR",
    "cal_0p1pct_precision": "cal 0.1% precision",
    "cal_0p1pct_f1": "cal 0.1% F1",
}


def _spread(s: pd.Series, pct: bool) -> str:
    k = 100 if pct else 1
    digits = 1 if pct else 4
    return f"{s.median() * k:.{digits}f} [{s.min() * k:.{digits}f}, {s.max() * k:.{digits}f}]"


def _label(row: pd.Series, family: str) -> str:
    model = row["model"]
    feats = row.get("features")
    if family == "tier A":
        return f"{model} ({feats})"
    return model if family in ("tier B", "blend") else family


def cal_summary(tables: Path) -> pd.DataFrame:
    rows = []
    for name, family in RUN_TABLES.items():
        path = tables / name
        if not path.exists():
            continue
        runs = pd.read_csv(path)
        runs = runs[runs["eval_set"].isin(EVAL_SETS)]
        runs = runs.assign(label=runs.apply(_label, axis=1, family=family))
        for (label, eval_set), g in runs.groupby(["label", "eval_set"], sort=False):
            out = {
                "source_table": name,
                "model": label,
                "eval_set": eval_set,
                "splits": g["split"].nunique(),
                "urls": int(g["n_urls"].median()),
                "negatives": int(g["n_neg"].median()),
            }
            for col, nice in CAL_COLS.items():
                out[nice] = _spread(g[col], pct=True)
            rows.append(out)
    return pd.DataFrame(rows)


def depth_summary(tables: Path) -> pd.DataFrame:
    path = tables / "tier_a_depth.csv"
    if not path.exists():
        return pd.DataFrame()
    d = pd.read_csv(path, dtype={"depth": str})
    rows = []
    for (model, feats, depth), g in d.groupby(["model", "features", "depth"], sort=False):
        rows.append(
            {
                "model": f"{model} ({feats})",
                "depth": depth,
                "splits": g["split"].nunique(),
                "urls": int(g["n_urls"].median()),
                "phishing": int(g["n_pos"].median()),
                "negatives": int(g["n_neg"].median()),
                "ROC-AUC": _spread(g["roc_auc"], pct=False),
                "recall @1% FPR": _spread(g["op_1pct_recall"], pct=True),
                "recall @0.1% FPR": _spread(g["op_0p1pct_recall"], pct=True),
                "0.1% granularity-limited splits": int(g["op_0p1pct_granularity_limited"].sum()),
                "cal 1% recall / FPR": f"{g['cal_1pct_recall'].median() * 100:.1f} / "
                f"{g['cal_1pct_fpr'].median() * 100:.1f}",
            }
        )
    return pd.DataFrame(rows)


def _md(df: pd.DataFrame) -> str:
    if df.empty:
        return "_no input table found_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines) + "\n"


def render(cal: pd.DataFrame, depth: pd.DataFrame) -> str:
    cal_view = cal.drop(columns=["source_table"]) if not cal.empty else cal
    return (
        "# Summary tables\n\n"
        "Generated by `python -m experiments.summary_tables` from the per-split run tables in "
        "`reports/tables/`. Do not edit by hand. Values are the median [min, max] over splits, "
        "in %.\n\n"
        "## At the calibration-side thresholds\n\n"
        "Thresholds chosen on each split's calibration side for 1% and 0.1% FPR, applied unchanged "
        "to each evaluation set (what a deployed model does). `negatives` is the median number of "
        "benign URLs behind each FPR.\n\n"
        + _md(cal_view)
        + "\n## Depth-matched evaluation (tier A, test side)\n\n"
        "Recall at fixed FPR measured inside each URL-depth bucket (non-empty path segments). A "
        "point whose FPR budget allows fewer than 10 false positives (floor(target x negatives)) "
        "is granularity-limited (`experiments/metrics.py`); the column counts the splits where "
        "that happened at 0.1%.\n\n" + _md(depth)
    )


def run(reports: Path) -> Path:
    tables = reports / "tables"
    cal, depth = cal_summary(tables), depth_summary(tables)
    cal.to_csv(tables / "summary_cal.csv", index=False)
    depth.to_csv(tables / "summary_depth.csv", index=False)
    out = reports / "summary.md"
    out.write_text(render(cal, depth), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.summary_tables")
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    a = ap.parse_args(argv)
    print(run(a.reports))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
