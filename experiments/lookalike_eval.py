"""What the offline look-alike check adds, measured without a browser.

``python -m experiments.lookalike_eval --ood PATH/ood_urls.csv [--regional FILE] [--feed FILE]``

Runs ``js/bench/lookalike.mjs`` (bundled allowlist, tier A model, then the look-alike rule through
the extension's own combiner; no page, backend or blocklist) over:

- false alarms: the natural legitimate pages (``ok`` rows of the out-of-distribution set), regional
  brand sites (one URL per line), and the own domains of the brands in ``brands.txt`` (``brand.com``
  as a stand-in for the real site, which the rule must leave alone);
- look-alikes made from names by ``attacks`` and small seeded edits: ASCII look-alike characters,
  punycode look-alike letters, one letter off, brand + word, TLD swap. They are made twice: from
  brands that are on ``brands.txt`` ("listed") and from site names of the natural pages that are
  not ("unlisted"). The rule can only know listed brands, so the unlisted rows show what the rest
  of the system does on its own and keep the listed rows from being read as general coverage;
- real phishing hosts from a feed file, to see that nothing breaks.

Writes ``reports/lookalike.md`` and ``reports/tables/lookalike.csv``. Fixed seed.
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
import tempfile
from pathlib import Path

import pandas as pd

from attacks import apply_family
from features.lists import ROOT, load_lists
from phishdrift.domains import split_host

BENCH = ROOT / "js" / "bench" / "lookalike.mjs"
ALLOWLIST = ROOT / "extension" / "data" / "allowlist.json"
SEED = 0
SWAP_TLDS = ("com", "net", "org", "info", "xyz", "top")
WORDS = ("login", "secure", "verify", "account")
ALPHABET = "abcdefghijklmnopqrstuvwxyz"


def run_node(urls: list[str]) -> pd.DataFrame:
    subprocess.run(["node", str(ROOT / "extension" / "build.mjs")], check=True, capture_output=True)
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8") as f:
        f.write("\n".join(urls))
    out = subprocess.run(
        ["node", str(BENCH), f.name, str(ALLOWLIST)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    Path(f.name).unlink()
    return pd.DataFrame(json.loads(out.stdout))


def edit_one(name: str, rng: random.Random) -> str:
    """One deletion, swap, substitution or insertion inside the name (not at its first letter)."""
    i = rng.randrange(1, len(name))
    kind = rng.choice(("delete", "swap", "substitute", "insert"))
    if kind == "delete":
        return name[:i] + name[i + 1 :]
    if kind == "swap" and i + 1 < len(name):
        return name[:i] + name[i + 1] + name[i] + name[i + 2 :]
    if kind == "substitute":
        return name[:i] + rng.choice(ALPHABET.replace(name[i], "")) + name[i + 1 :]
    return name[:i] + rng.choice(ALPHABET) + name[i:]


def families(names: list[str], lists) -> dict[str, list[str]]:
    """Look-alike URLs of every family for the given site names (one URL per name and family)."""
    rng = random.Random(SEED)
    out: dict[str, list[str]] = {
        k: [] for k in ("ascii", "punycode", "one_letter", "brand_word", "tld_swap")
    }
    for name in names:
        base = f"https://www.{name}.com/login"
        h = apply_family("homoglyph", base, lists, SEED)
        if h:
            out["punycode" if "xn--" in h else "ascii"].append(h)
        w = edit_one(name, rng)
        if w != name:
            out["one_letter"].append(f"https://www.{w}.com/login")
        out["brand_word"].append(f"https://{name}-{rng.choice(WORDS)}.com/login")
        out["tld_swap"].append(f"https://www.{name}.{rng.choice(SWAP_TLDS[1:])}/login")
    return out


def read_urls(path: Path) -> list[str]:
    return [
        u.strip()
        for u in path.read_text(encoding="utf-8").splitlines()
        if u.strip().startswith("http")
    ]


def summarise(name: str, kind: str, d: pd.DataFrame) -> dict:
    n = len(d)
    return {
        "set": name,
        "kind": kind,
        "urls": n,
        "warned_before": int((d["before"] != "safe").sum()),
        "warned_after": int((d["after"] != "safe").sum()),
        "rule_hits": int(d["rule"].notna().sum()),
        "rule_hits_not_allowlisted": int((d["rule"].notna() & ~d["allowlisted"]).sum()),
        "on_allowlist": int(d["allowlisted"].sum()),
    }


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def render(rows: list[dict], hits: pd.DataFrame) -> str:
    lines = [
        "# Offline look-alike check",
        "",
        "Generated by `python -m experiments.lookalike_eval`. Do not edit by hand.",
        "Each URL goes through the bundled allowlist, the tier A model at its suspicious level and "
        "the look-alike rule (`js/src/lookalike.js`) in the extension's combiner. No page, "
        "backend or blocklist is applied, so a hit raises safe to suspicious and no further. "
        "Fixed seed.",
        "",
        "| set | kind | URLs | on allowlist | warned before | warned after | rule hits "
        "(allowlist ignored) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['set']} | {r['kind']} | {r['urls']:,} | {r['on_allowlist']:,} "
            f"| {r['warned_before']} "
            f"({_pct(r['warned_before'], r['urls'])}) | {r['warned_after']} "
            f"({_pct(r['warned_after'], r['urls'])}) | {r['rule_hits']} |"
        )
    if len(hits):
        lines += [
            "",
            "## Rule hits on legitimate sets (false alarms)",
            "",
            "| set | url | rule | brand | on allowlist |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {r.set} | {r.url} | {r.rule} | {r.brand} | {r.allowlisted} |"
            for r in hits.itertuples()
        ]
    lines.append("")
    return "\n".join(lines)


def run(
    reports: Path, ood: Path, regional: Path | None, feed: Path | None, domains: dict[str, Path]
) -> Path:
    lists = load_lists()
    nat = pd.read_csv(ood)
    nat = nat[nat["ok"].astype(str).str.lower() == "true"]
    natural_urls = nat["url"].drop_duplicates().tolist()
    brands = sorted(b for b in lists.brands if b.isalpha() and len(b) >= 4)
    brand_set = set(lists.brands)
    unlisted = sorted(
        {
            split_host(d)[1]
            for d in nat["domain"].unique()
            if split_host(d)[1].isalpha()
            and len(split_host(d)[1]) >= 4
            and split_host(d)[1] not in brand_set
        }
    )
    sets: list[tuple[str, str, list[str]]] = [
        ("natural legitimate pages", "legit", natural_urls),
        ("brand own sites (brand.com)", "legit", [f"https://www.{b}.com/" for b in brands]),
    ]
    if regional is not None:
        sets.append(("regional brand sites", "legit", read_urls(regional)))
    for tag, names in (("listed brands", brands), ("unlisted names", unlisted)):
        for fam, urls in families(names, lists).items():
            sets.append((f"{fam}, {tag}", "look-alike", urls))
    for name, path in domains.items():
        sets.append((name, "legit", [f"https://{d}/" for d in path.read_text().split()]))
    if feed is not None:
        sets.append(("real phishing feed hosts", "phishing", read_urls(feed)))
    rows, hits = [], []
    for name, kind, urls in sets:
        d = run_node(urls)
        rows.append(summarise(name, kind, d))
        if kind == "legit":
            hits.append(d[d["rule"].notna()].assign(set=name))
    tables = reports / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(tables / "lookalike.csv", index=False)
    out = reports / "lookalike.md"
    out.write_text(render(rows, pd.concat(hits)), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.lookalike_eval")
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--ood", type=Path, required=True)
    ap.add_argument("--regional", type=Path, default=None)
    ap.add_argument("--feed", type=Path, default=None)
    ap.add_argument(
        "--domains",
        nargs=2,
        action="append",
        metavar=("NAME", "FILE"),
        default=[],
        help="a legitimate domain list (one per line) as a false-alarm set",
    )
    a = ap.parse_args(argv)
    print(run(a.reports, a.ood, a.regional, a.feed, {n: Path(f) for n, f in a.domains}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
