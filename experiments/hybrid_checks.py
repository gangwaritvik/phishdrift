"""Representation check and shuffled-label control for the hybrid tier A model.

python -m experiments.hybrid_checks [--processed ...] [--reports reports] [--splits ...]

Per split k:
- ``test_normalised``: the real hybrid model scored on ``https://www.<registrable domain>`` for
  each test domain and label (L1 representation check), with the cal-side thresholds;
- ``control``: the hybrid trained on permuted training labels (unweighted, see
  ``experiments.tier_a``) and scored on test (L11). A mean ROC-AUC further than
  ``eval.shuffled_label_flag`` from 0.5 is flagged.

Each split writes ``tables/hybrid_checks/split_<k>.csv``; ``hybrid_checks.md`` is rebuilt from
all of them. Finished splits are skipped on a rerun.
"""

from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import numpy as np
import pandas as pd

from data_pipeline.split import CAL, TEST, TRAIN
from experiments.hybrid_a import VARIANTS, make_hybrid
from experiments.metrics import evaluate, operating_point
from experiments.tier_a import (
    _fmt,
    apply_fitted,
    assert_no_overlap,
    load_part,
    normalised_features,
    refit,
)
from features.lists import Lists, load_lists
from phishdrift.config import load_config

log = logging.getLogger("hybrid_checks")


def run_split(
    k: int,
    pool: pd.DataFrame,
    splits: pd.DataFrame,
    norm: pd.DataFrame,
    lists,
    cfg,
    variant="hybrid",
):
    ev = cfg["eval"]
    targets, min_neg = ev["target_fprs"], ev["min_negatives"]
    side = splits[f"split_{k}"].to_numpy()
    train, cal, test = (pool[side == s] for s in (TRAIN, CAL, TEST))
    assert_no_overlap(train, test, "train", "test")
    assert_no_overlap(train, cal, "train", "cal")
    t0 = time.monotonic()
    fitted = refit(train, lists)
    train, cal, test = (apply_fitted(f, fitted) for f in (train, cal, test))
    y, w = train["label"].to_numpy(), train["weight"].to_numpy()

    model = make_hybrid(cfg, variant).fit(train, y, w)
    s_cal = model.score(cal)
    thresholds = {t: operating_point(cal["label"], s_cal, t, min_neg)["threshold"] for t in targets}
    test_norm = test.drop_duplicates(["domain", "label"])[["domain", "label", "depth"]]
    norm_feats = apply_fitted(norm.loc[test_norm["domain"]].reset_index(drop=True), fitted)
    test_norm = pd.concat([test_norm.reset_index(drop=True), norm_feats], axis=1)
    s_norm = model.score(test_norm)
    rows = [
        {"split": k, "check": "test_normalised", "n_domains": test_norm["domain"].nunique()}
        | evaluate(test_norm["label"].to_numpy(), s_norm, targets, min_neg, thresholds)
    ]
    log.info("split %d normalised: %.0fs", k, time.monotonic() - t0)

    y_shuffled = np.random.default_rng(cfg["seed"] + k).permutation(y)
    control = make_hybrid(cfg, variant).fit(train, y_shuffled)
    rows.append(
        {"split": k, "check": "control", "n_domains": test["domain"].nunique()}
        | evaluate(test["label"].to_numpy(), control.score(test), targets, min_neg)
    )
    log.info("split %d checks: %.0fs", k, time.monotonic() - t0)
    return rows


def render(runs: pd.DataFrame, cfg: dict, variant: str = "hybrid") -> str:
    flag = cfg["eval"]["shuffled_label_flag"]
    norm = runs[runs["check"] == "test_normalised"]
    ctrl = runs[runs["check"] == "control"]
    mean_auc = ctrl["roc_auc"].mean()
    lines = [
        f"# Hybrid tier A model ({variant}): representation check and shuffled-label control",
        "",
        "Generated by `python -m experiments.hybrid_checks`. Do not edit by hand.",
        "",
        "## Test URLs normalised to `https://www.<registrable domain>`",
        "",
        f"{len(norm)} splits; per split (median) {int(norm['n_urls'].median()):,} URLs from "
        f"{int(norm['n_domains'].median()):,} domains.",
        "Median [min, max].",
        "",
        "| ROC-AUC | recall @1% FPR | recall @0.1% FPR | cal 1%: recall / FPR |",
        "|---|---|---|---|",
    ]

    def cell(g: pd.DataFrame, m: str, pct: bool = True) -> str:
        return f"{_fmt(g[m].median(), pct)} [{_fmt(g[m].min(), pct)}, {_fmt(g[m].max(), pct)}]"

    lines.append(
        f"| {cell(norm, 'roc_auc', False)} | {cell(norm, 'op_1pct_recall')} "
        f"| {cell(norm, 'op_0p1pct_recall')} "
        f"| {_fmt(norm['cal_1pct_recall'].median())} / {_fmt(norm['cal_1pct_fpr'].median())} |"
    )
    lines += [
        "",
        "## Shuffled-label control (test)",
        "",
        "| splits | mean ROC-AUC | min | max | flagged |",
        "|---|---|---|---|---|",
        f"| {len(ctrl)} | {mean_auc:.4f} | {ctrl['roc_auc'].min():.4f} "
        f"| {ctrl['roc_auc'].max():.4f} | {'YES' if abs(mean_auc - 0.5) > flag else 'no'} |",
        "",
    ]
    return "\n".join(lines)


def _names(variant: str) -> tuple[str, str]:
    """(runs folder, report stem) of a variant: the first hybrid keeps its original names."""
    return ("hybrid_checks",) * 2 if variant == "hybrid" else (f"{variant}_checks",) * 2


def write_reports(reports: Path, cfg: dict, variant: str = "hybrid") -> Path:
    folder, stem = _names(variant)
    parts = sorted((reports / "tables" / folder).glob("split_*.csv"))
    runs = pd.concat([pd.read_csv(p) for p in parts], ignore_index=True)
    runs.to_csv(reports / "tables" / f"{stem}.csv", index=False)
    out = reports / f"{stem}.md"
    out.write_text(render(runs, cfg, variant), encoding="utf-8")
    return out


def run(
    processed: Path,
    reports: Path,
    split_ids: list[int] | None = None,
    cfg: dict | None = None,
    lists: Lists | None = None,
    variant: str = "hybrid",
) -> Path:
    cfg = cfg or load_config("models")
    lists = lists or load_lists()
    per_split = reports / "tables" / _names(variant)[0]
    per_split.mkdir(parents=True, exist_ok=True)
    pool = load_part(processed, "pool", lists)
    splits = pd.read_parquet(processed / "splits.parquet")
    splits = pool[["uid"]].merge(splits, on="uid", how="left", validate="one_to_one")
    n_splits = sum(c.startswith("split_") for c in splits.columns)
    norm = normalised_features(pool["domain"], lists)
    for k in split_ids if split_ids is not None else range(n_splits):
        out = per_split / f"split_{k}.csv"
        if out.exists():
            continue
        tmp = out.with_suffix(".tmp")
        rows = run_split(k, pool, splits, norm, lists, cfg, variant)
        pd.DataFrame(rows).to_csv(tmp, index=False)
        tmp.replace(out)
        write_reports(reports, cfg, variant)
        log.info("split %d written", k)
    return write_reports(reports, cfg, variant)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.hybrid_checks")
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--splits", type=int, nargs="*", default=None)
    ap.add_argument("--variant", choices=sorted(VARIANTS), default="hybrid")
    ap.add_argument("--lists-dir", default=None)
    ap.add_argument("--platforms-file", default=None)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    lists = load_lists(a.lists_dir, a.platforms_file)
    print(run(a.processed, a.reports, a.splits, lists=lists, variant=a.variant))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
