"""Depth-matched evaluation of the shipped tier A model (hybrid2) on test, held-out source and
time slice.

python -m experiments.hybrid_depth [--processed data/processed] [--reports reports] [--splits ...]

Per split k the hybrid2 model is trained on the train side exactly as in ``experiments.hybrid_a``
and its FPR thresholds come from the cal side. Every evaluation set is then cut into URL-depth
buckets (non-empty path segments, 0 / 1 / 2 / 3 / 4+), and each bucket gets ROC-AUC, recall at
fixed FPR on its own operating points, and the recall and FPR the cal-side thresholds give inside
it. A model that leans on depth (the PhiUSIIL "homepage = benign" shortcut, report L4) scores well
overall but poorly inside a bucket; PhishStorm's depth 0 is mostly phishing and its depth 4+ mostly
phishing too, so its overall score needs this view. A bucket whose FPR budget allows fewer than
10 false positives is granularity-limited (``experiments/metrics.py``).
One result file per split (``tables/hybrid2_depth/split_<k>.csv``); writes ``hybrid2_depth.md``.
"""

from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import pandas as pd

from data_pipeline.split import CAL, TEST, TRAIN
from experiments.hybrid_a import make_hybrid
from experiments.metrics import evaluate, operating_point
from experiments.tier_a import (
    PARTS,
    apply_fitted,
    assert_no_overlap,
    depth_bucket,
    load_part,
    refit,
)
from features.lists import load_lists
from phishdrift.config import load_config

log = logging.getLogger("hybrid_depth")
VARIANT = "hybrid2"


def run_split(k, pool, splits, holdouts, lists, cfg) -> list[dict]:
    ev = cfg["eval"]
    targets, min_neg, top = ev["target_fprs"], ev["min_negatives"], ev["depth_top_bucket"]
    side = splits[f"split_{k}"].to_numpy()
    train, cal, test = (pool[side == s] for s in (TRAIN, CAL, TEST))
    for name, other in {"cal": cal, "test": test, **holdouts}.items():
        assert_no_overlap(train, other, "train", name)
    t0 = time.monotonic()
    fitted = refit(train, lists)
    train, cal, test = (apply_fitted(f, fitted) for f in (train, cal, test))
    holdouts = {n: apply_fitted(h, fitted) for n, h in holdouts.items()}
    model = make_hybrid(cfg, VARIANT).fit(
        train, train["label"].to_numpy(), train["weight"].to_numpy()
    )
    s_cal = model.score(cal)
    thr = {t: operating_point(cal["label"], s_cal, t, min_neg)["threshold"] for t in targets}
    rows = []
    for set_name, frame in {"test": test, **holdouts}.items():
        s = model.score(frame)
        y = frame["label"].to_numpy()
        buckets = depth_bucket(frame["depth"], top).to_numpy()
        for b in ["all", *sorted(set(buckets))]:
            m = buckets == buckets if b == "all" else buckets == b
            r = evaluate(y[m], s[m], targets, min_neg, thr)
            n_dom = frame.loc[m, "domain"].nunique()
            rows.append({"split": k, "eval_set": set_name, "depth": b, "n_domains": n_dom} | r)
    log.info("split %d: %.0fs", k, time.monotonic() - t0)
    return rows


def _cell(g: pd.DataFrame, col: str, pct: bool) -> str:
    v = g[col].dropna()
    if v.empty:
        return "n/a"
    k, d = (100, 1) if pct else (1, 4)
    return f"{v.median() * k:.{d}f} [{v.min() * k:.{d}f}, {v.max() * k:.{d}f}]"


def _med(g: pd.DataFrame, col: str, digits: int = 1) -> str:
    v = g[col].dropna()
    return "n/a" if v.empty else f"{v.median() * 100:.{digits}f}"


def render(runs: pd.DataFrame) -> str:
    lines = [
        "# Depth-matched evaluation of hybrid2 (the shipped tier A model)",
        "",
        "Generated by `python -m experiments.hybrid_depth`. Do not edit by hand.",
        "Median [min, max] over splits. Depth = non-empty path segments. `op` recall uses the "
        "bucket's own operating point; `cal` uses the thresholds chosen on the cal side (what "
        "the extension does). `*` = granularity-limited at 0.1% in at least one split.",
        "",
        "| set | depth | splits | phishing | benign | ROC-AUC | op recall @1% | op recall @0.1% "
        "| cal 1%: recall / FPR | cal 0.1%: recall / FPR |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (set_name, depth), g in runs.groupby(["eval_set", "depth"], sort=False):
        star = "*" if g["op_0p1pct_granularity_limited"].astype(bool).any() else ""
        lines.append(
            f"| {set_name} | {depth} | {g['split'].nunique()} | {int(g['n_pos'].median()):,} "
            f"| {int(g['n_neg'].median()):,} | {_cell(g, 'roc_auc', False)} "
            f"| {_cell(g, 'op_1pct_recall', True)} | {_cell(g, 'op_0p1pct_recall', True)}{star} "
            f"| {_med(g, 'cal_1pct_recall')} / {_med(g, 'cal_1pct_fpr')} "
            f"| {_med(g, 'cal_0p1pct_recall')} / {_med(g, 'cal_0p1pct_fpr', 2)} |"
        )
    lines.append("")
    return "\n".join(lines)


def write_reports(reports: Path) -> Path:
    files = sorted((reports / "tables" / "hybrid2_depth").glob("split_*.csv"))
    runs = pd.concat([pd.read_csv(f, dtype={"depth": str}) for f in files], ignore_index=True)
    order = {"test": 0, "heldout_source": 1, "time_slice": 2}
    runs = runs.sort_values(
        ["eval_set", "depth"], key=lambda c: c.map(order) if c.name == "eval_set" else c
    )
    runs.to_csv(reports / "tables" / "hybrid2_depth_runs.csv", index=False)
    out = reports / "hybrid2_depth.md"
    out.write_text(render(runs), encoding="utf-8")
    return out


def run(processed: Path, reports: Path, split_ids=None, cfg=None, lists=None) -> Path:
    cfg = cfg or load_config("models")
    lists = lists or load_lists()
    out_dir = reports / "tables" / "hybrid2_depth"
    out_dir.mkdir(parents=True, exist_ok=True)
    frames = {p: load_part(processed, p, lists) for p in PARTS}
    pool = frames.pop("pool")
    splits = pd.read_parquet(processed / "splits.parquet")
    splits = pool[["uid"]].merge(splits, on="uid", how="left", validate="one_to_one")
    n_splits = sum(c.startswith("split_") for c in splits.columns)
    for k in split_ids if split_ids is not None else range(n_splits):
        out = out_dir / f"split_{k}.csv"
        if out.exists():
            continue
        rows = run_split(k, pool, splits, frames, lists, cfg)
        tmp = out.with_suffix(".tmp")
        pd.DataFrame(rows).to_csv(tmp, index=False)
        tmp.replace(out)
    return write_reports(reports)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.hybrid_depth")
    ap.add_argument("--processed", type=Path, default=Path("data/processed"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--splits", type=int, nargs="*", default=None)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--lists-dir", default=None)
    ap.add_argument("--platforms-file", default=None)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s: %(message)s")
    if a.report_only:
        print(write_reports(a.reports))
        return 0
    lists = load_lists(a.lists_dir, a.platforms_file)
    print(run(a.processed, a.reports, a.splits, lists=lists))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
