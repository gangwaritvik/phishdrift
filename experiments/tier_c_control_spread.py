"""Why the tier C shuffled-label control has a wide split-to-split spread.

python -m experiments.tier_c_control_spread --features FILE [--until YYYY-MM-DD] [--out DIR]

Reuses the tier C eligibility filters, splits and booster of ``experiments/tier_c.py`` and checks,
per split: the control as reported (5 shuffles), the same scores against randomly permuted test
labels (what a label-blind score would give), weaker/stronger control models, and the
single-feature test AUCs. Writes ``tier_c_control_spread.md`` (every number from this run).
"""

from __future__ import annotations

import argparse
import copy
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from data_pipeline.split import TEST, TRAIN, grouped_splits
from experiments.tier_c import eligible
from features.registry import NAMES_C
from models.gbdt import GBDT
from phishdrift.config import load_config

VARIANTS = {
    "as reported (300 trees, 15 leaves, min leaf 10)": {},
    "min leaf 200": {"min_child_samples": 200},
    "30 trees": {"n_estimators": 30},
    "stumps (2 leaves), 300 trees": {"num_leaves": 2},
}


def run(features: Path, until: str | None, out: Path, variant_shuffles: int = 3) -> Path:
    cfg = load_config("models")
    cc = cfg["tier_c"]
    df, _ = eligible(pd.read_parquet(features), cc["max_capture_lag_h"], cc["require_resolving"])
    if until:
        df = df[df["captured_at"].dt.strftime("%Y-%m-%d") <= until].reset_index(drop=True)
    sp = grouped_splits(df, cc["n_splits"], cc["test_fraction"], cc["cal_fraction"], cc["seed"])
    rows, uni, dup = [], {}, []
    for k in range(cc["n_splits"]):
        side = sp[f"split_{k}"]
        tr, te = (df[(side == s).to_numpy()] for s in (TRAIN, TEST))
        y, seed = te["label"].to_numpy(), cc["seed"] + k
        for f in NAMES_C:  # missing is a value, as in the trees
            x = np.nan_to_num(te[f].to_numpy(float), nan=-1e9)
            if len(np.unique(x)) > 1:
                uni.setdefault(f, []).append(roc_auc_score(y, x))
        key = lambda d: pd.util.hash_pandas_object(d[list(NAMES_C)].round(3), index=False)  # noqa: E731
        k_tr, k_te = key(tr), key(te)
        twin = k_te.isin(set(k_tr)).to_numpy()
        dup.append((y, twin, (k_te.map(k_te.value_counts()) > 1).to_numpy()))
        for name, over in VARIANTS.items():
            p = copy.deepcopy(cc["lightgbm"]) | over
            n = cc["control_shuffles"] if not over else variant_shuffles
            for j in range(n):
                ys = np.random.default_rng(seed + 1000 * j).permutation(tr["label"].to_numpy())
                s = GBDT("lightgbm", p, list(NAMES_C), seed).fit(tr, ys).score(te)
                perm = np.random.default_rng(seed + 777 + j).permutation(y)
                rows.append(
                    {
                        "split": k,
                        "variant": name,
                        "shuffle": j,
                        "auc": roc_auc_score(y, s),
                        "auc_permuted_test_labels": roc_auc_score(perm, s),
                        "n_pos": int(y.sum()),
                        "n_neg": int((y == 0).sum()),
                    }
                )
        print("split", k, flush=True)
    r = pd.DataFrame(rows)
    out.mkdir(parents=True, exist_ok=True)
    r.to_csv(out / "tier_c_control_spread.csv", index=False)
    n_pos, n_neg = int(r["n_pos"].median()), int(r["n_neg"].median())
    null_sd = float(np.sqrt((n_pos + n_neg + 1) / (12 * n_pos * n_neg)))
    ys_all = np.concatenate([d[0] for d in dup])
    twin_all = np.concatenate([d[1] for d in dup])
    dup_all = np.concatenate([d[2] for d in dup])
    lines = [
        "# Tier C shuffled-label control: why the spread is wide",
        "",
        "Generated by `python -m experiments.tier_c_control_spread`. Do not edit by hand.",
        f"Rows: {len(df):,} eligible domains ({int(df['label'].sum()):,} phishing), "
        f"captured up to {until or 'the last capture day'}; "
        f"{cc['n_splits']} registrable-domain-grouped splits, test side median {n_pos} phishing / "
        f"{n_neg:,} benign.",
        "",
        "## Control AUC by model strength",
        "",
        "| control model | runs | mean AUC | SD | min | max | vs permuted test labels: mean / SD |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, g in r.groupby("variant", sort=False):
        a, pm = g["auc"], g["auc_permuted_test_labels"]
        lines.append(
            f"| {name} | {len(g)} | {a.mean():.3f} | {a.std():.3f} | {a.min():.3f} | {a.max():.3f} "
            f"| {pm.mean():.3f} / {pm.std():.3f} |"
        )
    base = r[r["variant"] == next(iter(VARIANTS))]
    per = base.groupby("split")["auc"].agg(["mean", "std"])
    lines += [
        "",
        f"Expected SD of a test AUC if the scores were independent of the labels: {null_sd:.4f} "
        f"(formula for {n_pos} / {n_neg:,}). Observed SD of the reported control: "
        f"{base['auc'].std():.3f}, i.e. as if only about "
        f"{1 / (12 * base['auc'].std() ** 2):.0f} independent positives were being ranked "
        "(heuristic: n = 1 / (12 SD^2)).",
        f"Between splits (SD of the 10 split means): {per['mean'].std():.3f}; within a split, "
        f"across shuffles (mean SD): {per['std'].mean():.3f}.",
        "",
        "## Where the positives sit",
        "",
        "Test phishing rows with an identical feature vector in train: "
        f"{twin_all[ys_all == 1].mean():.1%} (benign {twin_all[ys_all == 0].mean():.1%}). "
        "With an identical twin elsewhere in the same test side: "
        f"{dup_all[ys_all == 1].mean():.1%} (benign {dup_all[ys_all == 0].mean():.1%}).",
        "",
        "Strongest single features on the test side (AUC of the raw feature value, median of the "
        "splits; 0.5 = no signal; below 0.5 means lower values are phishing):",
        "",
        "| feature | AUC |",
        "|---|---|",
    ]
    u = pd.Series({f: float(np.median(v)) for f, v in uni.items()})
    for f in (u - 0.5).abs().sort_values(ascending=False).index[:8]:
        lines.append(f"| `{f}` | {u[f]:.3f} |")
    lines += [
        "",
        "## Reading",
        "",
        "- Permuting the test labels instead gives mean 0.5 and the SD of the formula above, so "
        "ties, the AUC code and the test size are not the cause.",
        "- The spread comes from the model's noise being a function of the features, while the "
        "real phishing rows differ from benign ones in many correlated features at once. Whichever "
        "way the noise leans in that region sets the AUC for the whole split.",
        "- If that is right, a simpler (smoother) control model should spread more, not less. "
        "Compare the rows of the first table.",
        "- Not tested here: whether the mean below 0.5 is a real bias or chance (the mean's "
        "standard error is wide because the splits share the same rows).",
        "",
    ]
    path = out / "tier_c_control_spread.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--features", type=Path, required=True)
    ap.add_argument("--until", default=None)
    ap.add_argument("--out", type=Path, default=Path("reports"))
    a = ap.parse_args(argv)
    print(run(a.features, a.until, a.out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
