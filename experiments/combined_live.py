"""Summarise js/bench/combined_live.mjs rows: verdict rates per class for the tier sets A, A+B, A+C, A+B+C.

    python -m experiments.combined_live --rows PATH/rows.csv --out reports/combined_live.md

Every number comes from the rows file (one row per address); nothing is typed by hand. Intervals are Wilson 95%.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

SETS = [("A", "address model only"), ("AB", "address + page"), ("AC", "address + domain"), ("ABC", "address + page + domain (as shipped)"), ("ABC_all", "address + page + domain, domain asked for every address")]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)


def cell(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}] ({k}/{n})" if n else "n/a"


def table(df: pd.DataFrame, mode: str) -> list[str]:
    out = ["| tier set | class | n | domains | dangerous | warned (suspicious or dangerous) |", "|---|---|---|---|---|---|"]
    for key, name in SETS:
        col = f"v_{key}_{mode}"
        for label, cls in [(1, "phishing"), (0, "legitimate")]:
            sub = df[df.label == label]
            n = len(sub)
            out.append(f"| {key}: {name} | {cls} | {n} | {sub.domain.nunique()} | {cell(int((sub[col] == 'dangerous').sum()), n)} | {cell(int((sub[col] != 'safe').sum()), n)} |")
    return out


def moves(df: pd.DataFrame, mode: str, a: str, b: str) -> list[str]:
    out = []
    for label, cls in [(1, "phishing"), (0, "legitimate")]:
        sub = df[df.label == label]
        ct = pd.crosstab(sub[f"v_{a}_{mode}"], sub[f"v_{b}_{mode}"]).reindex(index=["safe", "suspicious", "dangerous"], columns=["safe", "suspicious", "dangerous"], fill_value=0)
        out.append(f"{cls}: rows = {a}, columns = {b}")
        out.append("")
        out.append("| | safe | suspicious | dangerous |")
        out.append("|---|---|---|---|")
        for i, r in ct.iterrows():
            out.append(f"| {i} | {r['safe']} | {r['suspicious']} | {r['dangerous']} |")
        out.append("")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", required=True)
    ap.add_argument("--out", default="reports/combined_live.md")
    args = ap.parse_args()
    df = pd.read_csv(args.rows)
    for col in ["fetch_ok", "shared", "allow", "shortener", "redirected_cross_domain", "asks_credentials"]:
        if col in df:
            df[col] = df[col].fillna(False).astype(str).str.lower().eq("true")
    L: list[str] = ["# Combined three-tier measurement on live addresses", "", f"Source: `{args.rows}` ({len(df)} addresses). Generated by `experiments/combined_live.py`.", ""]

    L += ["## What was available", "", "| | phishing | legitimate |", "|---|---|---|"]
    ph, lg = df[df.label == 1], df[df.label == 0]
    both = lambda f: (f(ph), f(lg))  # noqa: E731
    rows_av = [
        ("addresses (one per registrable domain)", lambda d: f"{len(d)} ({d.domain.nunique()} domains)"),
        ("page fetched (HTTP 2xx, HTML)", lambda d: f"{int(d.fetch_ok.sum())}"),
        ("page read by the page model", lambda d: f"{int((d.page_state == 'scored').sum())}"),
        ("tier C answered", lambda d: f"{int((d.c_state == 'scored').sum())}"),
        ("tier C not applicable (hosting platform / shortener / IP)", lambda d: f"{int(d.c_state.astype(str).str.startswith('not_checked:hosting').sum() + d.c_state.astype(str).str.startswith('not_checked:shortener').sum() + d.c_state.astype(str).str.startswith('not_checked:ip').sum())}"),
        ("tier C unreachable or failed", lambda d: f"{int((~d.c_state.astype(str).isin(['scored']) & ~d.c_state.astype(str).str.startswith('not_checked:hosting') & ~d.c_state.astype(str).str.startswith('not_checked:shortener') & ~d.c_state.astype(str).str.startswith('not_checked:ip')).sum())}"),
        ("all three tiers available", lambda d: f"{int(((d.page_state == 'scored') & (d.c_state == 'scored')).sum())}"),
        ("on the bundled allowlist", lambda d: f"{int(d.allow.sum())}"),
        ("redirected to another domain", lambda d: f"{int(d.redirected_cross_domain.sum())}"),
    ]
    for name, f in rows_av:
        a, b = both(f)
        L.append(f"| {name} | {a} | {b} |")
    L.append("")
    if "source" in df:
        L += ["Phishing by feed: " + ", ".join(f"{k} {v}" for k, v in ph.source.value_counts().items()), ""]
    L += ["Tier C states, phishing: " + ", ".join(f"{k} {v}" for k, v in ph.c_state.value_counts().items()), "", "Tier C states, legitimate: " + ", ".join(f"{k} {v}" for k, v in lg.c_state.value_counts().items()), ""]
    L += ["Fetch errors, phishing: " + ", ".join(f"{k or 'none'} {v}" for k, v in ph.fetch_error.fillna("none").value_counts().head(8).items()), "", "Fetch errors, legitimate: " + ", ".join(f"{k or 'none'} {v}" for k, v in lg.fetch_error.fillna("none").value_counts().head(8).items()), ""]

    full = df[(df.page_state == "scored") & (df.c_state == "scored")]
    for mode, title in [("off", "allowlist off (the models' own behaviour, as the evaluation rules require)"), ("on", "allowlist on (as shipped)")]:
        L += [f"## {title}", "", "### All addresses (a tier that is unavailable for an address simply does not contribute)", ""] + table(df, mode) + [""]
        L += [f"### Only addresses where all three tiers answered ({len(full[full.label == 1])} phishing, {len(full[full.label == 0])} legitimate)", ""] + table(full, mode) + [""]
        L += ["### What the page and the domain check changed (all addresses)", ""] + moves(df, mode, "A", "ABC")
    if "layer_ABC_off" in df:
        L += ["### Deciding layer of the shipped combination, allowlist off", "", "| layer | phishing | legitimate |", "|---|---|---|"]
        for lay in sorted(df.layer_ABC_off.dropna().unique()):
            L.append(f"| {lay} | {int((ph.layer_ABC_off == lay).sum())} | {int((lg.layer_ABC_off == lay).sum())} |")
        L.append("")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
