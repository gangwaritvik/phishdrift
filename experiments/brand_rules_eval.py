"""How often the brand and look-alike rules fire on legitimate and on phishing addresses and pages.

python -m experiments.brand_rules_eval --ood-csv data/raw/ood/ood_urls.csv \
    --ood-html data/raw/ood_html/pages [--regional FILE] [--phishing FILE ...] [--reports reports]

The rules can only raise a verdict, so the question for each set is how often they fire:
on legitimate sets every firing is a false alarm the rules add (before the allowlist, which the
extension applies first; the allowlisted share is reported next to it when ``--allowlist`` is
given), on phishing sets every firing is a catch. Sets:

- natural legitimate pages (``ood_urls.csv``, evaluation only): address rules on every URL; the
  brand-page rule on the pages with stored HTML;
- regional brand sites (``--regional``, one URL per line): address rules;
- phishing URL lists (``--phishing``, one URL per line, e.g. fresh feed URLs): address rules.

Also the phishing_catcher-style host score (``catcher_score``) as a baseline: its threshold is the
99th / 99.9th percentile of the natural legitimate URLs' scores (so it flags 1% / 0.1% of them by
construction) and its catch rate on each phishing list at those thresholds.

Writes ``reports/brand_rules.md`` and ``reports/tables/brand_rules_*.csv``. No model, no training.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import pandas as pd

from features.brand_rules import RULES, catcher_score, load_config, load_rules
from features.html_features import analyze
from features.lists import load_lists


def read_urls(path: Path) -> list[str]:
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]


def address_table(urls: list[str], set_name: str, rules, cfg) -> pd.DataFrame:
    rows = []
    for u in urls:
        hits = rules.address_signals(u)
        rows.append(
            {
                "set": set_name,
                "url": u,
                "rule": hits[0]["rule"] if hits else "",
                "brand": hits[0]["brand"] if hits else "",
                "catcher": catcher_score(u, rules, cfg["catcher"]),
            }
        )
    return pd.DataFrame(rows)


def page_table(pages: pd.DataFrame, rules, lists) -> pd.DataFrame:
    rows = []
    brands = frozenset(rules.brands)
    for url, html in zip(pages["url"], pages["html"], strict=True):
        facts: dict = {}
        _, status = analyze(url, html, lists=lists, facts=facts, fact_brands=brands)
        sig = rules.page_signal(url, facts) if facts else None
        rows.append(
            {
                "url": url,
                "status": status,
                "parsed": bool(facts),
                "credential": bool(facts) and any(
                    facts.get(k, 0) for k in ("password_fields", "otp_fields", "card_fields", "pin_fields")  # noqa: E501
                ),
                "brand_claimed": bool(facts)
                and bool(facts["title_brands"] or facts["site_brands"] or facts["copyright_brands"]),  # noqa: E501
                "fired": sig is not None,
                "brand": sig["brand"] if sig else "",
            }
        )  # fmt: skip
    return pd.DataFrame(rows)


def _pct(k: int, n: int) -> str:
    return f"{k} / {n} ({100 * k / n:.2f}%)" if n else "0 / 0"


def render(addr: pd.DataFrame, page: pd.DataFrame | None, thresholds: dict, args) -> str:
    out = ["# Brand and look-alike rules", ""]
    out.append(
        "Generated by `python -m experiments.brand_rules_eval`. Rules: `features/brand_rules.py` "
        "(same answers in `js/src/brand_rules.js`, checked by `tests/fixtures/brand_rules_parity.json`). "  # noqa: E501
        "They only raise a verdict, so on legitimate sets every firing is an added false alarm and on "  # noqa: E501
        "phishing sets every firing is a catch. Measured with the allowlist off unless a column says so."  # noqa: E501
    )
    out += ["", "## Address rules", ""]
    out.append("| set | URLs | domains | any rule | " + " | ".join(RULES) + " |")
    out.append("|---|---|---|---|" + "---|" * len(RULES))
    for name, g in addr.groupby("set", sort=False):
        n = len(g)
        doms = g["url"].map(lambda u: u.split("/")[2] if "//" in u else u).nunique()
        cells = [_pct(int((g["rule"] != "").sum()), n)]
        cells += [str(int((g["rule"] == r).sum())) for r in RULES]
        out.append(f"| {name} | {n} | {doms} | " + " | ".join(cells) + " |")
    fired = addr[addr["rule"] != ""]
    legit = fired[~fired["set"].str.startswith("phishing")]
    out += ["", "Legitimate URLs the address rules fire on (all of them):", ""]
    if legit.empty:
        out.append("- none")
    for _, r in legit.iterrows():
        out.append(f"- `{r['url']}` ({r['set']}): {r['rule']} {r['brand']}")
    if page is not None:
        out += ["", "## Brand-page rule on natural legitimate pages", ""]
        n = len(page)
        out.append(f"- pages with stored HTML: {n}; parsed: {int(page['parsed'].sum())}")
        out.append(f"- with a password, OTP, card or PIN field: {int(page['credential'].sum())}")
        out.append(
            f"- naming a brand in title, og:site_name or copyright: {int(page['brand_claimed'].sum())}"  # noqa: E501
        )
        out.append(f"- **rule fires (false alarms added): {_pct(int(page['fired'].sum()), n)}**")
        for _, r in page[page["fired"]].iterrows():
            out.append(f"  - `{r['url']}`: {r['brand']}")
    out += ["", "## Baseline: phishing_catcher-style host score", ""]
    out.append(
        "Thresholds are the 99th and 99.9th percentiles of the natural legitimate URLs' scores, so "
        "they flag 1% and 0.1% of those URLs by construction (an in-sample threshold, which favours "  # noqa: E501
        "the baseline)."
    )
    out.append("")
    out.append("| set | URLs | flagged at legit 1% | flagged at legit 0.1% |")
    out.append("|---|---|---|---|")
    for name, g in addr.groupby("set", sort=False):
        s = g["catcher"].dropna()
        out.append(
            f"| {name} | {len(s)} | {_pct(int((s > thresholds['p99']).sum()), len(s))} | "
            f"{_pct(int((s > thresholds['p999']).sum()), len(s))} |"
        )
    out.append("")
    out.append(f"Thresholds: 1% = {thresholds['p99']:.1f}, 0.1% = {thresholds['p999']:.1f}.")
    return "\n".join(out) + "\n"


def run(args) -> Path:
    rules, cfg, lists = load_rules(), load_config(), load_lists()
    ood = pd.read_csv(args.ood_csv)
    if "ok" in ood:
        ood = ood[ood["ok"].astype(bool)]
    parts = [address_table(ood["url"].tolist(), "natural legitimate", rules, cfg)]
    if args.regional:
        parts.append(address_table(read_urls(args.regional), "regional brand sites", rules, cfg))
    for path in args.phishing or []:
        parts.append(address_table(read_urls(path), f"phishing: {Path(path).name}", rules, cfg))
    addr = pd.concat(parts, ignore_index=True)
    page = None
    if args.ood_html:
        files = (
            sorted(Path(args.ood_html).glob("*.parquet"))
            if Path(args.ood_html).is_dir()
            else [Path(args.ood_html)]
        )
        pages = pd.concat(
            [pd.read_parquet(f, columns=["url", "html"]) for f in files], ignore_index=True
        )
        pages = pages[pages["url"].isin(set(ood["url"]))].drop_duplicates("url")
        page = page_table(pages, rules, lists)
    legit_scores = addr.loc[addr["set"] == "natural legitimate", "catcher"].dropna().to_numpy()
    thresholds = {
        "p99": float(np.quantile(legit_scores, 0.99)) if len(legit_scores) else math.nan,
        "p999": float(np.quantile(legit_scores, 0.999)) if len(legit_scores) else math.nan,
    }
    reports = Path(args.reports)
    (reports / "tables").mkdir(parents=True, exist_ok=True)
    addr.to_csv(reports / "tables" / "brand_rules_address.csv", index=False)
    if page is not None:
        page.to_csv(reports / "tables" / "brand_rules_pages.csv", index=False)
    out = reports / "brand_rules.md"
    out.write_text(render(addr, page, thresholds, args), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ood-csv", type=Path, required=True)
    ap.add_argument("--ood-html", type=Path, default=None, help="pages parquet file or directory")
    ap.add_argument("--regional", type=Path, default=None)
    ap.add_argument("--phishing", type=Path, nargs="*", default=None)
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    print(run(ap.parse_args(argv)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
