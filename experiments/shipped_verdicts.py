"""What the shipped extension's first layers say about natural legitimate pages, without a browser.

``python -m experiments.shipped_verdicts --ood data/raw/ood/ood_urls.csv [--tranco FILE]``

Runs ``js/bench/verdicts.mjs`` (the bundled allowlist, then the tier A model at its suspicious and
dangerous thresholds, in the order of ``extension/src/background.js``) over the natural
legitimate pages of the out-of-distribution set (``ok`` rows only) and, when a Tranco file is given,
over the ``https://www.<domain>`` homepages of its top sites. The blocklist, backend and page
layers are not applied, and no site is visited: this is a measurement of the shipped lists and
model on known-legitimate URLs, not a browsing test. Writes ``reports/shipped_verdicts.md`` and
``reports/tables/shipped_verdicts.csv``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BENCH = ROOT / "js" / "bench" / "verdicts.mjs"
ALLOWLIST = ROOT / "extension" / "data" / "allowlist.json"


def load_urls(ood: Path) -> pd.DataFrame:
    d = pd.read_csv(ood)
    d = d[d["ok"].astype(str).str.lower() == "true"]
    return d[["url", "domain"]].drop_duplicates("url").reset_index(drop=True)


def tranco_homepages(path: Path, top: int) -> pd.DataFrame:
    d = pd.read_csv(path, header=None, names=["rank", "domain"], nrows=top)
    return pd.DataFrame({"url": "https://www." + d["domain"], "domain": d["domain"]})


def run_node(urls: list[str]) -> pd.DataFrame:
    subprocess.run(["node", str(ROOT / "extension" / "build.mjs")], check=True, capture_output=True)
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False, encoding="utf-8") as f:
        f.write("\n".join(urls))
    out = subprocess.run(
        ["node", str(BENCH), f.name, str(ALLOWLIST)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    Path(f.name).unlink()
    return pd.DataFrame(json.loads(out.stdout))


def summarise(name: str, d: pd.DataFrame) -> dict:
    n_na = int((~d["allowlisted"]).sum())
    flagged_model = d[d["model"] != "safe"]
    flagged_ship = d[d["shipped"] != "safe"]
    return {
        "set": name,
        "urls": len(d),
        "domains": d["domain"].nunique(),
        "allowlisted_urls": int(d["allowlisted"].sum()),
        "model_suspicious": int((d["model"] == "suspicious").sum()),
        "model_dangerous": int((d["model"] == "dangerous").sum()),
        "shipped_suspicious": int((d["shipped"] == "suspicious").sum()),
        "shipped_dangerous": int((d["shipped"] == "dangerous").sum()),
        "shipped_flagged_domains": flagged_ship["domain"].nunique(),
        "not_allowlisted_urls": n_na,
        "not_allowlisted_flagged": int(((d["shipped"] != "safe") & ~d["allowlisted"]).sum()),
        "model_flagged": len(flagged_model),
    }


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def render(rows: list[dict], flagged: pd.DataFrame) -> str:
    lines = [
        "# Shipped extension on natural legitimate pages",
        "",
        "Generated by `python -m experiments.shipped_verdicts`. Do not edit by hand.",
        "Each URL goes through the bundled allowlist (Tranco top 50,000) and then the tier A model "
        "at its suspicious (1% FPR) and dangerous (0.1% FPR) thresholds, in the order the "
        "extension uses. No page was visited and the blocklist, backend and page layers are not "
        "applied: this is a measurement on known-legitimate URLs, not a browsing test.",
        "",
        "| set | URLs | domains | on allowlist | model alone: suspicious / dangerous | "
        "shipped: suspicious / dangerous | shipped flagged | not on allowlist: flagged |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        shipped = r["shipped_suspicious"] + r["shipped_dangerous"]
        lines.append(
            f"| {r['set']} | {r['urls']:,} | {r['domains']:,} | {r['allowlisted_urls']:,} "
            f"({_pct(r['allowlisted_urls'], r['urls'])}) "
            f"| {r['model_suspicious']} / {r['model_dangerous']} "
            f"({_pct(r['model_flagged'], r['urls'])}) "
            f"| {r['shipped_suspicious']} / {r['shipped_dangerous']} "
            f"| {shipped} ({_pct(shipped, r['urls'])}, {r['shipped_flagged_domains']} domains) "
            f"| {r['not_allowlisted_flagged']} of {r['not_allowlisted_urls']:,} "
            f"({_pct(r['not_allowlisted_flagged'], r['not_allowlisted_urls'])}) |"
        )
    lines += [
        "",
        "Caveats:",
        "- Some of the natural-page sites were seeded from Tranco, so the share on the allowlist "
        "is higher than for an average browsing history; the last column is the rate a visitor "
        "meets on sites outside the top 50,000.",
        "- The Tranco rows not on the allowlist are shared-hosting, CDN and shortener domains "
        "(amazonaws.com, github.io, bit.ly, ...) and open-hosting domains learned from phishing "
        "hosts (weebly.com, ...) that the allowlist leaves out by design, so a page there is "
        "judged by the model or the blocklist.",
        "- The model's own false-alarm rate on these pages with the allowlist off is the "
        "`model alone` column (also in `reports/ood_fpr.md`).",
        "",
    ]
    if len(flagged):
        lines += ["## Pages still flagged after the allowlist (natural pages)", ""]
        lines += ["| domain | flagged URLs | worst verdict |", "|---|---|---|"]
        g = (
            flagged.groupby("domain")
            .agg(
                n=("url", "size"),
                worst=(
                    "shipped",
                    lambda s: "dangerous" if (s == "dangerous").any() else "suspicious",
                ),
            )
            .sort_values(["worst", "n"], ascending=[True, False])
            .head(40)
        )
        lines += [f"| {dom} | {r.n} | {r.worst} |" for dom, r in g.iterrows()]
        lines.append("")
    return "\n".join(lines)


def run(reports: Path, ood: Path, tranco: Path | None, top: int) -> Path:
    sets = {"natural legitimate pages (ood_urls)": load_urls(ood)}
    if tranco is not None:
        sets[f"Tranco top {top:,} homepages"] = tranco_homepages(tranco, top)
    rows, per_url = [], []
    for name, urls in sets.items():
        res = run_node(urls["url"].tolist()).merge(urls, on="url", how="left")
        rows.append(summarise(name, res))
        per_url.append(res.assign(set=name))
    allp = pd.concat(per_url)
    flagged = allp[(allp["set"] == next(iter(sets))) & (allp["shipped"] != "safe")]
    tables = reports / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(tables / "shipped_verdicts.csv", index=False)
    out = reports / "shipped_verdicts.md"
    out.write_text(render(rows, flagged), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="experiments.shipped_verdicts")
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--ood", type=Path, required=True)
    ap.add_argument("--tranco", type=Path, default=None)
    ap.add_argument("--top", type=int, default=1000)
    a = ap.parse_args(argv)
    print(run(a.reports, a.ood, a.tranco, a.top))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
